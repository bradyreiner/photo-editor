#pragma once

#include <QColor>
#include <QImage>
#include <QSize>
#include <QString>

namespace photo_editor::desktop {

// Converts an alpha- or luminance-driven source matte into a smooth-scaled
// white RGBA image with the matte coverage in its alpha channel. Luminance is
// Rec.709 over linearized sRGB, multiplied by source alpha before inversion.
// If target_size is invalid, the original matte dimensions are retained.
[[nodiscard]] QImage timeline_source_matte_alpha(
    const QImage& matte,
    const QString& mode,
    bool invert,
    const QSize& target_size = QSize{},
    QString* error_message = nullptr);

// Builds a deterministic FFmpeg chain for a clip's source alpha multiplied
// by the generated matte alpha. If fill_color is valid, the source RGB is
// replaced with that flat color and source alpha is multiplied by its alpha
// before the matte is applied. The caller must supply mask_alpha_label as a
// looping RGBA PNG generated by timeline_source_matte_alpha(), with source
// and matte inputs on the same frame clock.
[[nodiscard]] QString timeline_source_matte_ffmpeg_chain(
    const QString& source_label,
    const QString& matte_alpha_label,
    const QString& output_label,
    const QString& unique_prefix,
    const QSize& target_size,
    const QColor& fill_color = QColor{},
    QString* error_message = nullptr);

}  // namespace photo_editor::desktop
