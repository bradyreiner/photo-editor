                                         NSUInteger uniforms_index,
                                         const void* payload,
                                         std::size_t payload_size) {
        id<MTLComputeCommandEncoder> encoder =
            [command_buffer computeCommandEncoder];
        [encoder setComputePipelineState:pipeline];
        for (auto buffer_index = std::size_t{0U};
             buffer_index < buffers.size(); ++buffer_index) {
          [encoder setBuffer:buffers[buffer_index]
                      offset:0
                     atIndex:static_cast<NSUInteger>(buffer_index)];
        }
        if (payload_size > 0U) {
          [encoder setBytes:payload length:payload_size atIndex:uniforms_index];
        }
        auto group_size = std::min<NSUInteger>(
            pipeline.maxTotalThreadsPerThreadgroup, 256U);
        [encoder dispatchThreads:MTLSizeMake(pixel_count, 1U, 1U)
             threadsPerThreadgroup:MTLSizeMake(group_size, 1U, 1U)];
        [encoder endEncoding];
        ++kernel_dispatch_count;
      };
      const auto dispatch_fill = [&](const FillLayerUniforms& active_uniforms,
                                     id<MTLBuffer> intermediate_buffer) {
        id<MTLBuffer> uniform_buffer = [impl_->device
            newBufferWithBytes:&active_uniforms
                         length:sizeof(active_uniforms)
                        options:MTLResourceStorageModeShared];
        if (uniform_buffer == nil) return false;
        dispatch_buffers(
            impl_->fill_layer_pipeline,
            std::array<id<MTLBuffer>, 9U>{
                pixel_buffer, fill_mask_buffer, layer_pixel_buffer,
                layer_tone_buffer, layer_curve_buffer, layer_look_buffer,
                uniform_buffer, layer_alpha_buffer, intermediate_buffer},
            9U, nullptr, 0U);
        return true;
      };
      const auto box_blur = [&](id<MTLBuffer> input, id<MTLBuffer> output,
                                int radius) {
        const auto blur = BlurUniforms{width, height, radius};
        dispatch_buffers(
            impl_->blur_horizontal_pipeline,
            std::array<id<MTLBuffer>, 2U>{input, spatial_scratch_buffer},
            2U, &blur, sizeof(blur));
        dispatch_buffers(
            impl_->blur_vertical_pipeline,
            std::array<id<MTLBuffer>, 2U>{spatial_scratch_buffer, output},
            2U, &blur, sizeof(blur));
      };
      const auto guided_blur = [&](id<MTLBuffer> input, id<MTLBuffer> output,
                                   int radius, float epsilon) {
        const auto guided = GuidedFilterUniforms{
            .pixel_count = static_cast<std::uint32_t>(pixel_count),
            .epsilon = epsilon};
        box_blur(input, detail_lightness_buffer, radius);
        dispatch_buffers(
            impl_->guided_square_pipeline,
            std::array<id<MTLBuffer>, 2U>{input, spatial_haze_buffer},
            2U, &guided, sizeof(guided));
        box_blur(spatial_haze_buffer, detail_chroma_a_buffer, radius);
        dispatch_buffers(
            impl_->guided_coefficients_pipeline,
            std::array<id<MTLBuffer>, 5U>{
                input, detail_lightness_buffer, detail_chroma_a_buffer,
                detail_chroma_b_buffer, detail_blur_a_buffer},
            5U, &guided, sizeof(guided));
        box_blur(detail_chroma_b_buffer, detail_blur_b_buffer, radius);
        box_blur(detail_blur_a_buffer, spatial_haze_buffer, radius);
        dispatch_buffers(
            impl_->guided_compose_pipeline,
            std::array<id<MTLBuffer>, 4U>{
                input, detail_blur_b_buffer, spatial_haze_buffer, output},
            4U, &guided, sizeof(guided));
      };
      const auto apply_layer_spatial = [&](const CompiledFillLayer& layer,
                                           id<MTLBuffer> target_buffer) {
        const auto spatial = RetainedSpatialDetailUniforms{
            .luminance_red = static_cast<float>(
                fill_layer_program.rgb_to_xyz_native.values[3]),
            .luminance_green = static_cast<float>(
                fill_layer_program.rgb_to_xyz_native.values[4]),
            .luminance_blue = static_cast<float>(
                fill_layer_program.rgb_to_xyz_native.values[5]),
            .texture_strength = layer.texture,
            .clarity_strength = layer.clarity,
            .dehaze_strength = 0.0F,
            .output_headroom = fill_layer_program.output_headroom,
            .width = fill_layer_program.width,
            .height = fill_layer_program.height,
            .active_mask =
                (std::abs(layer.texture) > 1.0e-6F ? 1U : 0U) | 2U};
        dispatch_buffers(
            impl_->retained_spatial_luminance_pipeline,
            std::array<id<MTLBuffer>, 2U>{
                target_buffer, spatial_luminance_buffer},
            2U, &spatial, sizeof(spatial));
        if (std::abs(layer.dehaze) > 1.0e-9F) {
          uniforms.source_only = 3U;
          if (!dispatch_fill(uniforms, target_buffer)) return false;
        }
        if ((spatial.active_mask & 1U) != 0U) guided_blur(
            spatial_luminance_buffer, spatial_texture_buffer, 2, 0.00045F);
        guided_blur(
            spatial_luminance_buffer, spatial_clarity_buffer, 8, 0.0018F);
        dispatch_buffers(
            impl_->retained_spatial_detail_pipeline,
            std::array<id<MTLBuffer>, 5U>{
                target_buffer, spatial_luminance_buffer,
                spatial_texture_buffer, spatial_clarity_buffer,
                spatial_haze_buffer},
            5U, &spatial, sizeof(spatial));
        return true;
      };
      const auto apply_layer_fine = [&](std::size_t layer_index,
                                        id<MTLBuffer> target_buffer) {
        const auto& program = fill_layer_program.fine_detail_programs[layer_index];
        auto detail = RetainedFineDetailUniforms{
            .sharpen_strength = program.sharpen_strength,
            .sharpen_gain = program.sharpen_gain,
            .sharpen_radius_fraction = program.sharpen_radius_fraction,
            .sharpen_subpixel_scale = program.sharpen_subpixel_scale,
            .sharpen_mask_strength = program.sharpen_mask_strength,
            .luminance_nr_strength = program.luminance_nr_strength,
            .color_nr_strength = program.color_nr_strength,
            .width = program.width, .height = program.height,
            .active_mask = program.active_mask};
        for (auto matrix_index = std::size_t{0U}; matrix_index < 9U; ++matrix_index) {
          detail.rgb_to_xyz_d65[matrix_index] = static_cast<float>(
              program.rgb_to_xyz_d65.values[matrix_index]);
          detail.xyz_d65_to_rgb[matrix_index] = static_cast<float>(
              program.xyz_d65_to_rgb.values[matrix_index]);
        }
        dispatch_buffers(
            impl_->retained_detail_extract_pipeline,
            std::array<id<MTLBuffer>, 4U>{
                target_buffer, detail_lightness_buffer,
                detail_chroma_a_buffer, detail_chroma_b_buffer},
            4U, &detail, sizeof(detail));
        const auto blur_fine = [&](id<MTLBuffer> input, id<MTLBuffer> output,
                                   int radius) {
          auto source_buffer = input;
          for (const auto pass_radius : gaussian_approximation_radii(radius)) {
            if (pass_radius <= 0) continue;
            box_blur(source_buffer, output, pass_radius);
            source_buffer = output;
          }
        };
        if ((program.active_mask &
             CompiledFineDetailProgram::kLuminanceNoiseReduction) != 0U) {
          blur_fine(detail_lightness_buffer, detail_blur_a_buffer, 2);
          blur_fine(detail_lightness_buffer, detail_blur_b_buffer, 5);
          dispatch_buffers(
              impl_->retained_detail_luma_nr_pipeline,
              std::array<id<MTLBuffer>, 3U>{
                  detail_lightness_buffer, detail_blur_a_buffer,
                  detail_blur_b_buffer},
              3U, &detail, sizeof(detail));
        }
        if ((program.active_mask &
             CompiledFineDetailProgram::kColorNoiseReduction) != 0U) {
          blur_fine(detail_chroma_a_buffer, detail_blur_a_buffer, 3);
          blur_fine(detail_chroma_b_buffer, detail_blur_b_buffer, 3);
          dispatch_buffers(
              impl_->retained_detail_color_nr_pipeline,
              std::array<id<MTLBuffer>, 4U>{
                  detail_chroma_a_buffer, detail_chroma_b_buffer,
                  detail_blur_a_buffer, detail_blur_b_buffer},
              4U, &detail, sizeof(detail));
        }
        if ((program.active_mask & CompiledFineDetailProgram::kSharpen) != 0U) {
          blur_fine(detail_lightness_buffer, detail_blur_a_buffer,
                    static_cast<int>(program.sharpen_radius));
          blur_fine(detail_lightness_buffer, detail_blur_b_buffer,
                    static_cast<int>(program.sharpen_edge_radius));
          dispatch_buffers(
              impl_->retained_detail_sharpen_pipeline,
              std::array<id<MTLBuffer>, 3U>{
                  detail_lightness_buffer, detail_blur_a_buffer,
                  detail_blur_b_buffer},
              3U, &detail, sizeof(detail));
        }
        dispatch_buffers(
            impl_->retained_detail_compose_pipeline,
            std::array<id<MTLBuffer>, 4U>{
                target_buffer, detail_lightness_buffer,
                detail_chroma_a_buffer, detail_chroma_b_buffer},
            4U, &detail, sizeof(detail));
      };
      const auto apply_layer_geometry_program = [&](std::size_t layer_index) {
        const auto& program = fill_layer_program.geometry_programs[layer_index];
        const auto geometry_uniforms = GeometryStageUniforms{
            .distortion_strength = program.distortion_strength,
            .chromatic_aberration_strength =
                program.chromatic_aberration_strength,
            .vertical_perspective = program.vertical_perspective,
            .horizontal_perspective = program.horizontal_perspective,
            .transform_rotation = program.transform_rotation,
            .transform_scale = program.transform_scale,
            .transform_skew_x = program.transform_skew_x,
            .transform_skew_y = program.transform_skew_y,
            .liquify_strength = program.liquify_strength,
            .liquify_center_x = program.liquify_center_x,
            .liquify_center_y = program.liquify_center_y,
            .liquify_radius = program.liquify_radius,
            .center_x = program.center_x,
            .center_y = program.center_y,
            .maximum_radius = program.maximum_radius,
            .width = program.width,
            .height = program.height,
            .content_aware_crop_fill =
                program.content_aware_crop_fill ? 1U : 0U,
        };
        dispatch_buffers(
            impl_->geometry_stage_pipeline,
            std::array<id<MTLBuffer>, 2U>{
                layer_intermediate_buffer, geometry_buffer},
            2U, &geometry_uniforms, sizeof(geometry_uniforms));
      };
      const auto apply_layer_user_luts = [&](
          std::size_t layer_index, id<MTLBuffer> target_buffer) {
        const auto& program = fill_layer_program.user_lut_programs[layer_index];
        for (auto lut_index = std::size_t{0U};
             lut_index < program.luts.size(); ++lut_index) {
          const auto lut_uniforms = make_user_lut_stage_uniforms(
              program.luts[lut_index],
              static_cast<std::uint32_t>(pixel_count));
          dispatch_buffers(
              impl_->user_lut_stage_pipeline,
              std::array<id<MTLBuffer>, 2U>{
                  target_buffer, layer_user_lut_buffers[layer_index][lut_index]},
              2U, &lut_uniforms, sizeof(lut_uniforms));
        }
      };
      if (!apply_layer_user_lut && !apply_layer_geometry &&
          !apply_layer_spatial_detail &&
          !apply_layer_fine_detail) {
        if (!dispatch_fill(uniforms, layer_intermediate_buffer)) {
          fail("fused_fill_layer_uniform_buffer_allocation_failed");
          return {};
        }
      } else {
        for (auto layer_index = std::uint32_t{0U};
             layer_index < fill_layer_program.layer_count; ++layer_index) {
          uniforms.layer_begin = layer_index;
          uniforms.layer_end = layer_index + 1U;
          const auto& layer = fill_layer_program.layers[layer_index];
          if (!layer.has_user_lut && !layer.has_geometry &&
              !layer.has_spatial_detail &&
              !layer.has_fine_detail) {
            uniforms.source_only = uniforms.composite_only = 0U;
            if (!dispatch_fill(uniforms, layer_intermediate_buffer)) return {};
            continue;
          }
          uniforms.source_only = 1U; uniforms.composite_only = 0U;
          if (!dispatch_fill(uniforms, layer_intermediate_buffer)) return {};
          auto layer_source_buffer = layer_intermediate_buffer;
          if (layer.has_user_lut) {
            apply_layer_user_luts(layer_index, layer_source_buffer);
          }
          if (std::abs(layer.lens_vignette) > 1.0e-6F) {
            uniforms.source_only = 2U;
            if (!dispatch_fill(uniforms, layer_source_buffer)) return {};
          }
          if (layer.has_geometry) {
            apply_layer_geometry_program(layer_index);
            layer_source_buffer = geometry_buffer;
          }
          if (layer.has_spatial_detail) {
            if (!apply_layer_spatial(layer, layer_source_buffer)) return {};
          } else if (std::abs(layer.dehaze) > 1.0e-9F) {
            uniforms.source_only = 3U;
            if (!dispatch_fill(uniforms, layer_source_buffer)) return {};
          }
          if (layer.has_fine_detail) {
            apply_layer_fine(layer_index, layer_source_buffer);
          }
          uniforms.source_only = 0U; uniforms.composite_only = 1U;
          if (!dispatch_fill(uniforms, layer_source_buffer)) return {};
        }
      }
    }

    if (apply_spatial_detail) {
      const auto spatial_uniforms = RetainedSpatialDetailUniforms{
          .luminance_red =
              spatial_detail_program.luminance_coefficients[0],
          .luminance_green =
              spatial_detail_program.luminance_coefficients[1],
          .luminance_blue =
              spatial_detail_program.luminance_coefficients[2],
          .texture_strength = spatial_detail_program.texture_strength,
          .clarity_strength = spatial_detail_program.clarity_strength,
          .dehaze_strength = spatial_detail_program.dehaze_strength,
          .output_headroom = spatial_detail_program.output_headroom,
          .width = spatial_detail_program.width,
          .height = spatial_detail_program.height,
          .active_mask = spatial_detail_program.active_mask,
      };
      const auto dispatch_spatial = [&](id<MTLComputePipelineState> pipeline,
                                        const auto& encode_buffers,
                                        NSUInteger uniforms_index,
                                        const void* uniforms,
                                        std::size_t uniforms_size) {
        id<MTLComputeCommandEncoder> encoder =
            [command_buffer computeCommandEncoder];
        [encoder setComputePipelineState:pipeline];
        for (auto index = std::size_t{0U}; index < encode_buffers.size();
             ++index) {
          [encoder setBuffer:encode_buffers[index]
                      offset:0
                     atIndex:static_cast<NSUInteger>(index)];
        }
        [encoder setBytes:uniforms
                   length:uniforms_size
                  atIndex:uniforms_index];
        auto group_size = pipeline.maxTotalThreadsPerThreadgroup;
        group_size = std::min<NSUInteger>(group_size, 256U);
        [encoder dispatchThreads:MTLSizeMake(pixel_count, 1U, 1U)
             threadsPerThreadgroup:MTLSizeMake(group_size, 1U, 1U)];
        [encoder endEncoding];
        ++kernel_dispatch_count;
      };
      dispatch_spatial(
          impl_->retained_spatial_luminance_pipeline,
          std::array<id<MTLBuffer>, 2U>{
              pixel_buffer, spatial_luminance_buffer},
          2U,
          &spatial_uniforms,
          sizeof(spatial_uniforms));
      const auto blur_spatial = [&](int radius,
                                    id<MTLBuffer> destination,
                                    std::int64_t* dispatch_telemetry) {
        const auto blur_uniforms = BlurUniforms{
            .width = width,
            .height = height,
            .radius = radius,
        };
        dispatch_spatial(
            impl_->blur_horizontal_pipeline,
            std::array<id<MTLBuffer>, 2U>{
                spatial_luminance_buffer, spatial_scratch_buffer},
            2U,
            &blur_uniforms,
            sizeof(blur_uniforms));
        dispatch_spatial(
            impl_->blur_vertical_pipeline,
            std::array<id<MTLBuffer>, 2U>{
                spatial_scratch_buffer, destination},
            2U,
            &blur_uniforms,
            sizeof(blur_uniforms));
        if (dispatch_telemetry != nullptr) *dispatch_telemetry += 2;
      };
      if ((spatial_detail_program.active_mask &
           CompiledSpatialDetailProgram::kTexture) != 0U) {
        blur_spatial(
            2,
            spatial_texture_buffer,
            telemetry != nullptr
                ? &telemetry->gpu_spatial_texture_blur_dispatch_count
                : nullptr);
      }
      if ((spatial_detail_program.active_mask &
           CompiledSpatialDetailProgram::kClarity) != 0U) {
        blur_spatial(
            8,
            spatial_clarity_buffer,
            telemetry != nullptr
                ? &telemetry->gpu_spatial_clarity_blur_dispatch_count
                : nullptr);
      }
      if ((spatial_detail_program.active_mask &
           CompiledSpatialDetailProgram::kDehaze) != 0U) {
        blur_spatial(
            20,
            spatial_haze_buffer,
            telemetry != nullptr
                ? &telemetry->gpu_spatial_haze_blur_dispatch_count
                : nullptr);
      }
      dispatch_spatial(
          impl_->retained_spatial_detail_pipeline,
          std::array<id<MTLBuffer>, 5U>{
              pixel_buffer,
              spatial_luminance_buffer,
              spatial_texture_buffer,
              spatial_clarity_buffer,
              spatial_haze_buffer},
          5U,
          &spatial_uniforms,
          sizeof(spatial_uniforms));
    }

    if (apply_fine_detail) {
      auto detail_uniforms = RetainedFineDetailUniforms{
          .sharpen_strength = fine_detail_program.sharpen_strength,
          .sharpen_gain = fine_detail_program.sharpen_gain,
          .sharpen_radius_fraction = fine_detail_program.sharpen_radius_fraction,
          .sharpen_subpixel_scale = fine_detail_program.sharpen_subpixel_scale,
          .sharpen_mask_strength =
              fine_detail_program.sharpen_mask_strength,
          .luminance_nr_strength =
              fine_detail_program.luminance_nr_strength,
          .color_nr_strength = fine_detail_program.color_nr_strength,
          .width = fine_detail_program.width,
          .height = fine_detail_program.height,
          .active_mask = fine_detail_program.active_mask,
      };
      for (auto index = std::size_t{0U}; index < 9U; ++index) {
        detail_uniforms.rgb_to_xyz_d65[index] = static_cast<float>(
            fine_detail_program.rgb_to_xyz_d65.values[index]);
        detail_uniforms.xyz_d65_to_rgb[index] = static_cast<float>(
            fine_detail_program.xyz_d65_to_rgb.values[index]);
      }
      const auto dispatch_detail = [&](id<MTLComputePipelineState> pipeline,
                                       const auto& encode_buffers,
                                       NSUInteger uniforms_index,
                                       const void* uniforms,
                                       std::size_t uniforms_size) {
        id<MTLComputeCommandEncoder> encoder =
            [command_buffer computeCommandEncoder];
        [encoder setComputePipelineState:pipeline];
        for (auto index = std::size_t{0U}; index < encode_buffers.size();
             ++index) {
          [encoder setBuffer:encode_buffers[index]
                      offset:0
                     atIndex:static_cast<NSUInteger>(index)];
        }
        [encoder setBytes:uniforms
                   length:uniforms_size
                  atIndex:uniforms_index];
        auto group_size = pipeline.maxTotalThreadsPerThreadgroup;
        group_size = std::min<NSUInteger>(group_size, 256U);
        [encoder dispatchThreads:MTLSizeMake(pixel_count, 1U, 1U)
             threadsPerThreadgroup:MTLSizeMake(group_size, 1U, 1U)];
        [encoder endEncoding];
        ++kernel_dispatch_count;
      };
      dispatch_detail(
          impl_->retained_detail_extract_pipeline,
          std::array<id<MTLBuffer>, 4U>{
              pixel_buffer,
              detail_lightness_buffer,
              detail_chroma_a_buffer,
              detail_chroma_b_buffer},
          4U,
          &detail_uniforms,
          sizeof(detail_uniforms));
      const auto blur_detail = [&](id<MTLBuffer> source,
                                   id<MTLBuffer> destination,
                                   int radius) {
        auto current_source = source;
        for (const auto pass_radius :
             gaussian_approximation_radii(static_cast<double>(radius))) {
          if (pass_radius <= 0) continue;
          const auto blur_uniforms = BlurUniforms{
              .width = width,
              .height = height,
              .radius = pass_radius,
          };
          dispatch_detail(
              impl_->blur_horizontal_pipeline,
              std::array<id<MTLBuffer>, 2U>{
                  current_source, detail_scratch_buffer},
              2U,
              &blur_uniforms,
              sizeof(blur_uniforms));
          dispatch_detail(
              impl_->blur_vertical_pipeline,
              std::array<id<MTLBuffer>, 2U>{
                  detail_scratch_buffer, destination},
              2U,
              &blur_uniforms,
              sizeof(blur_uniforms));
          current_source = destination;
        }
      };
      if ((fine_detail_program.active_mask &
           CompiledFineDetailProgram::kLuminanceNoiseReduction) != 0U) {
        blur_detail(detail_lightness_buffer, detail_blur_a_buffer, 2);
        blur_detail(detail_lightness_buffer, detail_blur_b_buffer, 5);
        dispatch_detail(
            impl_->retained_detail_luma_nr_pipeline,
            std::array<id<MTLBuffer>, 3U>{
                detail_lightness_buffer,
                detail_blur_a_buffer,
                detail_blur_b_buffer},
            3U,
            &detail_uniforms,
            sizeof(detail_uniforms));
      }
      if ((fine_detail_program.active_mask &
           CompiledFineDetailProgram::kColorNoiseReduction) != 0U) {
        blur_detail(detail_chroma_a_buffer, detail_blur_a_buffer, 3);
        blur_detail(detail_chroma_b_buffer, detail_blur_b_buffer, 3);
        dispatch_detail(
            impl_->retained_detail_color_nr_pipeline,
            std::array<id<MTLBuffer>, 4U>{
                detail_chroma_a_buffer,
                detail_chroma_b_buffer,
                detail_blur_a_buffer,
                detail_blur_b_buffer},
            4U,
            &detail_uniforms,
            sizeof(detail_uniforms));
      }
      if ((fine_detail_program.active_mask &
           CompiledFineDetailProgram::kSharpen) != 0U) {
        blur_detail(
            detail_lightness_buffer,
            detail_blur_a_buffer,
            static_cast<int>(fine_detail_program.sharpen_radius));
        blur_detail(
            detail_lightness_buffer,
            detail_blur_b_buffer,
            static_cast<int>(fine_detail_program.sharpen_edge_radius));
        dispatch_detail(
            impl_->retained_detail_sharpen_pipeline,
            std::array<id<MTLBuffer>, 3U>{
                detail_lightness_buffer,
                detail_blur_a_buffer,
                detail_blur_b_buffer},
            3U,
            &detail_uniforms,
            sizeof(detail_uniforms));
      }
      dispatch_detail(
          impl_->retained_detail_compose_pipeline,
          std::array<id<MTLBuffer>, 4U>{
              pixel_buffer,
              detail_lightness_buffer,
              detail_chroma_a_buffer,
              detail_chroma_b_buffer},
          4U,
          &detail_uniforms,
          sizeof(detail_uniforms));
    }

    id<MTLBuffer> final_pixel_buffer = pixel_buffer;
    if (apply_geometry) {
      const auto geometry_uniforms = GeometryStageUniforms{
          .distortion_strength = geometry_program.distortion_strength,
          .chromatic_aberration_strength =
              geometry_program.chromatic_aberration_strength,
          .vertical_perspective =
              geometry_program.vertical_perspective,
          .horizontal_perspective =
              geometry_program.horizontal_perspective,
          .transform_rotation = geometry_program.transform_rotation,
          .transform_scale = geometry_program.transform_scale,
          .transform_skew_x = geometry_program.transform_skew_x,
          .transform_skew_y = geometry_program.transform_skew_y,
          .liquify_strength = geometry_program.liquify_strength,
          .liquify_center_x = geometry_program.liquify_center_x,
          .liquify_center_y = geometry_program.liquify_center_y,
          .liquify_radius = geometry_program.liquify_radius,
          .center_x = geometry_program.center_x,
          .center_y = geometry_program.center_y,
          .maximum_radius = geometry_program.maximum_radius,
          .width = geometry_program.width,
          .height = geometry_program.height,
          .content_aware_crop_fill =
              geometry_program.content_aware_crop_fill ? 1U : 0U,
      };
      id<MTLComputeCommandEncoder> geometry_encoder =
          [command_buffer computeCommandEncoder];
      [geometry_encoder
          setComputePipelineState:impl_->geometry_stage_pipeline];
      [geometry_encoder setBuffer:pixel_buffer offset:0 atIndex:0];
      [geometry_encoder setBuffer:geometry_buffer offset:0 atIndex:1];
      [geometry_encoder setBytes:&geometry_uniforms
                          length:sizeof(geometry_uniforms)
                         atIndex:2];
      auto geometry_group_size =
          impl_->geometry_stage_pipeline.maxTotalThreadsPerThreadgroup;
      geometry_group_size =
          std::min<NSUInteger>(geometry_group_size, 256U);
      [geometry_encoder
            dispatchThreads:MTLSizeMake(pixel_count, 1U, 1U)
          threadsPerThreadgroup:MTLSizeMake(
                                    geometry_group_size, 1U, 1U)];
      [geometry_encoder endEncoding];
      final_pixel_buffer = geometry_buffer;
      ++kernel_dispatch_count;
    }

    id<MTLSharedEvent> ready_event = [impl_->device newSharedEvent];
    if (ready_event == nil) {
      fail("fused_masks_color_lut_shared_event_unavailable");
      return {};
    }
    [command_buffer encodeSignalEvent:ready_event value:1U];
    [command_buffer addCompletedHandler:^(id<MTLCommandBuffer> completed) {
      if (completed.status != MTLCommandBufferStatusCompleted &&
          ready_event.signaledValue < 1U) {
        ready_event.signaledValue = 1U;
      }
    }];
    if (cancellation.cancelled()) {
      fail("fused_masks_color_lut_cancelled");
      return {};
    }
    [command_buffer commit];
    auto surface_impl = std::make_shared<MetalWorkingSurface::Impl>();
    surface_impl->pixel_buffer = final_pixel_buffer;
    surface_impl->producer_command_buffer = command_buffer;
    surface_impl->ready_event = ready_event;
    surface_impl->descriptor = descriptor;
    surface_impl->device_registry_id =
        static_cast<std::uint64_t>(impl_->device.registryID);
    surface_impl->ready_event_value = 1U;
    surface_impl->byte_size = static_cast<std::uint64_t>(buffer_size);
    if (telemetry != nullptr) {
      telemetry->gpu_fallback_reason.clear();
      telemetry->gpu_cpu_to_gpu_bytes +=
          static_cast<std::int64_t>(
              buffer_size +
              lut_upload_bytes +
              tone_lut_upload_bytes +
              curve_lut_upload_bytes +
              fill_mask_upload_bytes +
              layer_pixel_upload_bytes +
              layer_tone_upload_bytes +
              layer_curve_upload_bytes +
              layer_look_upload_bytes);
      telemetry->gpu_command_buffer_count += 1;
      telemetry->gpu_kernel_dispatch_count += kernel_dispatch_count;
    }
    return std::shared_ptr<const MetalWorkingSurface>(
        new MetalWorkingSurface(std::move(surface_impl)));
  }
}

bool MetalPipelineBackend::apply_masks_and_color_lut(
    std::vector<ColorPixel>* pixels,
    int width,
    int height,
    const ColorAdjustmentState& state,
    const ColorLut3D& lut,
    ColorAdjustmentTelemetry* telemetry,
    CancellationToken cancellation) {
  if (pixels == nullptr) {
    if (telemetry != nullptr) {
      telemetry->gpu_fallback_reason = "invalid_fused_masks_color_lut_request";
    }
    return false;
  }
  const auto descriptor = RenderSurfaceDescriptor{
      .pixel_encoding = RenderPixelEncoding::SceneLinearFloat,
      .color_domain = RenderColorDomain::WorkingScene,
      .range = RenderRangeModel::SceneExtended,
      .alpha = RenderAlphaModel::Straight,
      .color_space_identity = "metal-working-compatibility",
      .transfer_identity = "linear",
      .width = static_cast<std::uint32_t>(std::max(width, 0)),
      .height = static_cast<std::uint32_t>(std::max(height, 0)),
  };
  const auto surface = publish_masks_and_color_lut_surface(
      *pixels, width, height, state, lut, descriptor, telemetry, cancellation);
  auto materialized = std::vector<ColorPixel>{};
  if (surface == nullptr || !surface->copy_pixels(&materialized, cancellation)) {
    if (telemetry != nullptr && telemetry->gpu_fallback_reason.empty()) {
      telemetry->gpu_fallback_reason = cancellation.cancelled()
                                           ? "fused_masks_color_lut_cancelled"
                                           : "fused_masks_color_lut_command_buffer_failed";
    }
    return false;
  }
  *pixels = std::move(materialized);
  if (telemetry != nullptr) {
    telemetry->gpu_gpu_to_cpu_bytes +=
        static_cast<std::int64_t>(surface->byte_size());
  }
  return true;
}

std::vector<float> MetalPipelineBackend::gaussian_approximate_blur(
    const std::vector<float>& input,
    int width,
    int height,
    int radius) {
  if (!available() || input.empty() || width <= 0 || height <= 0 || radius <= 0) {
    return input;
  }

  const auto pixel_count = static_cast<std::size_t>(width * height);
  if (input.size() != pixel_count) {
    return input;
  }

  @autoreleasepool {
    const auto buffer_size = pixel_count * sizeof(float);
    id<MTLBuffer> source_buffer = [impl_->device newBufferWithLength:buffer_size
                                                             options:MTLResourceStorageModeShared];
    id<MTLBuffer> temp_buffer = [impl_->device newBufferWithLength:buffer_size
                                                           options:MTLResourceStorageModeShared];
    if (!source_buffer || !temp_buffer) {
      return input;
    }

    auto* source_data = static_cast<float*>([source_buffer contents]);
    std::copy(input.begin(), input.end(), source_data);

    id<MTLCommandBuffer> command_buffer = [impl_->command_queue commandBuffer];
    if (!command_buffer) {
      return input;
    }

    const auto dispatch_pass = [&](id<MTLComputePipelineState> pipeline,
                                   id<MTLBuffer> in_buffer,
                                   id<MTLBuffer> out_buffer,
                                   const BlurUniforms& uniforms) {
      id<MTLComputeCommandEncoder> encoder = [command_buffer computeCommandEncoder];
      [encoder setComputePipelineState:pipeline];
      [encoder setBuffer:in_buffer offset:0 atIndex:0];
      [encoder setBuffer:out_buffer offset:0 atIndex:1];
      [encoder setBytes:&uniforms length:sizeof(uniforms) atIndex:2];

      NSUInteger thread_group_size = pipeline.maxTotalThreadsPerThreadgroup;
      if (thread_group_size > 256) thread_group_size = 256;
      MTLSize grid_size = MTLSizeMake(pixel_count, 1, 1);
      MTLSize group_size = MTLSizeMake(thread_group_size, 1, 1);
      [encoder dispatchThreads:grid_size threadsPerThreadgroup:group_size];
      [encoder endEncoding];
    };

    id<MTLBuffer> current_input = source_buffer;
    id<MTLBuffer> current_output = temp_buffer;
    for (const auto pass_radius : gaussian_approximation_radii(static_cast<double>(radius))) {
      if (pass_radius <= 0) {
        continue;
      }

      const BlurUniforms uniforms{
          .width = width,
          .height = height,
          .radius = pass_radius,
      };
      dispatch_pass(impl_->blur_horizontal_pipeline, current_input, current_output, uniforms);
      std::swap(current_input, current_output);
      dispatch_pass(impl_->blur_vertical_pipeline, current_input, current_output, uniforms);
      std::swap(current_input, current_output);
    }
    [command_buffer commit];
    [command_buffer waitUntilCompleted];

    std::vector<float> output(pixel_count, 0.0F);
    const auto* result_data = static_cast<const float*>([current_input contents]);
    std::copy(result_data, result_data + pixel_count, output.begin());
    return output;
  }
}

