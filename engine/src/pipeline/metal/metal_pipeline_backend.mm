[[nodiscard]] const char* ocio_msl_texture_type(
    OcioProjectGpuTextureKind kind) {
  switch (kind) {
    case OcioProjectGpuTextureKind::OneDimensional:
      return "texture1d<float>";
    case OcioProjectGpuTextureKind::TwoDimensional:
      return "texture2d<float>";
    case OcioProjectGpuTextureKind::ThreeDimensional:
      return "texture3d<float>";
  }
  return "";
}

[[nodiscard]] std::string ocio_project_compute_shader_source(
    const OcioProjectGpuProgramDescription& program) {
  if (program.shader_text.empty() || program.function_name.empty() ||
      program.textures.size() > 64U) {
    return {};
  }
  std::set<std::size_t> bindings;
  auto shader_text = program.shader_text;
  // Hardware texture filtering quantizes interpolation weights on some GPUs.
  // Evaluate OCIO linear LUT interpolation in float, retaining its coordinates,
  // texel order and clamp-to-edge semantics. Nearest/tetrahedral lookups remain
  // as generated by OCIO.
  for (const auto& texture : program.textures) {
    if (texture.interpolation != "linear") {
      continue;
    }
    const auto lookup = texture.name + ".sample(" + texture.sampler_name + ", ";
    const auto replacement = "pe_ocio_sample_linear(" + texture.name + ", ";
    auto position = shader_text.find(lookup);
    if (position == std::string::npos) {
      return {};
    }
    do {
      shader_text.replace(position, lookup.size(), replacement);
      position = shader_text.find(lookup, position + replacement.size());
    } while (position != std::string::npos);
  }
  std::ostringstream source;
  source << "#include <metal_stdlib>\nusing namespace metal;\n"
         << R"(
float4 pe_ocio_sample_linear(texture1d<float> tex, float uv) {
  const uint last = tex.get_width() - 1u;
  const float p = clamp(uv * float(tex.get_width()) - 0.5f, 0.0f, float(last));
  const uint lo = uint(floor(p)), hi = min(lo + 1u, last);
  return mix(tex.read(lo), tex.read(hi), p - float(lo));
}
float4 pe_ocio_sample_linear(texture2d<float> tex, float2 uv) {
  const uint2 size(tex.get_width(), tex.get_height());
  const float2 p = clamp(uv * float2(size) - 0.5f, 0.0f, float2(size - 1u));
  const uint2 lo = uint2(floor(p)), hi = min(lo + 1u, size - 1u);
  const float2 f = p - float2(lo);
  return mix(mix(tex.read(lo), tex.read(uint2(hi.x, lo.y)), f.x),
             mix(tex.read(uint2(lo.x, hi.y)), tex.read(hi), f.x), f.y);
}
float4 pe_ocio_sample_linear(texture3d<float> tex, float3 uv) {
  const uint3 size(tex.get_width(), tex.get_height(), tex.get_depth());
  const float3 p = clamp(uv * float3(size) - 0.5f, 0.0f, float3(size - 1u));
  const uint3 lo = uint3(floor(p)), hi = min(lo + 1u, size - 1u);
  const float3 f = p - float3(lo);
  const float4 z0 = mix(
      mix(tex.read(lo), tex.read(uint3(hi.x, lo.y, lo.z)), f.x),
      mix(tex.read(uint3(lo.x, hi.y, lo.z)), tex.read(uint3(hi.x, hi.y, lo.z)), f.x), f.y);
  const float4 z1 = mix(
      mix(tex.read(uint3(lo.x, lo.y, hi.z)), tex.read(uint3(hi.x, lo.y, hi.z)), f.x),
      mix(tex.read(uint3(lo.x, hi.y, hi.z)), tex.read(hi), f.x), f.y);
  return mix(z0, z1, f.z);
}
)"
         << shader_text
         << "\nkernel void photo_editor_apply_ocio_project(\n"
         << "    device float4* pixels [[buffer(0)]],\n"
         << "    constant uint& pixel_count [[buffer(1)]]";
  for (const auto& texture : program.textures) {
    if (texture.name.empty() || texture.sampler_name.empty() ||
        texture.binding_index > 63U ||
        !bindings.insert(texture.binding_index).second) {
      return {};
    }
    source << ",\n    " << ocio_msl_texture_type(texture.kind) << ' '
           << texture.name << " [[texture(" << texture.binding_index
           << ")]],\n    sampler " << texture.sampler_name << " [[sampler("
           << texture.binding_index << ")]]";
  }
  source << ",\n    uint index [[thread_position_in_grid]])\n{\n"
         << "  if (index >= pixel_count) return;\n"
         << "  pixels[index] = " << program.function_name << '(';
  for (const auto& texture : program.textures) {
    source << texture.name << ", " << texture.sampler_name << ", ";
  }
  source << "pixels[index]);\n}\n";
  return source.str();
}

