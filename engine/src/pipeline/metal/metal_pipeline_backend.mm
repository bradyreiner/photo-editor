[[nodiscard]] UserLutStageUniforms make_user_lut_stage_uniforms(
    const CompiledUserLut& user_lut, std::uint32_t pixel_count) {
  auto uniforms = UserLutStageUniforms{
      .strength = user_lut.strength,
      .input_transfer = static_cast<std::uint32_t>(user_lut.input_transfer),
      .output_transfer = static_cast<std::uint32_t>(user_lut.output_transfer),
      .lut_size = static_cast<std::uint32_t>(user_lut.lut.size),
      .pixel_count = pixel_count,
      .shaper_input_min = static_cast<float>(user_lut.lut.shaper_input_range[0]),
      .shaper_input_max = static_cast<float>(user_lut.lut.shaper_input_range[1]),
      .shaper_size = static_cast<std::uint32_t>(user_lut.lut.shaper_size),
      .shaper_offset = static_cast<std::uint32_t>(user_lut.lut.table.size()),
  };
  for (auto index = std::size_t{0U}; index < 9U; ++index) {
    uniforms.working_to_input[index] =
        static_cast<float>(user_lut.working_to_input.values[index]);
    uniforms.output_to_working[index] =
        static_cast<float>(user_lut.output_to_working.values[index]);
  }
  for (auto channel = std::size_t{0U}; channel < 3U; ++channel) {
    const auto minimum = user_lut.lut.domain_min[channel];
    const auto maximum = user_lut.lut.domain_max[channel];
    const auto valid = std::isfinite(minimum) && std::isfinite(maximum) &&
                       maximum > minimum;
    uniforms.domain_min[channel] = valid ? static_cast<float>(minimum) : 0.0F;
    uniforms.domain_max[channel] = valid ? static_cast<float>(maximum) : 1.0F;
  }
  return uniforms;
}

