  float display_headroom;
  int black_point_compensation_enabled;
  int lut_size;
  int width;
  int height;
  int source_width;
  int source_origin_x;
  int source_origin_y;
};

static float3 multiply_matrix(constant float* matrix, float3 value) {
  return float3(
      matrix[0] * value.r + matrix[1] * value.g + matrix[2] * value.b,
      matrix[3] * value.r + matrix[4] * value.g + matrix[5] * value.b,
      matrix[6] * value.r + matrix[7] * value.g + matrix[8] * value.b);
}

static int lut_index(int size, int red, int green, int blue) {
  return (red * size + green) * size + blue;
}

static float3 tetrahedral_sample(
    device const float4* lut,
    int size,
    float3 coordinate) {
  float3 position = clamp(coordinate, 0.0f, 1.0f) * float(size - 1);
  int3 lower = min(int3(position), int3(size - 2));
  float3 f = position - float3(lower);
  float3 c000 = lut[lut_index(size, lower.r, lower.g, lower.b)].rgb;
  float3 c111 = lut[lut_index(size, lower.r + 1, lower.g + 1, lower.b + 1)].rgb;
  float3 v1;
  float3 v2;
  float4 weights;
  if (f.r >= f.g) {
    if (f.g >= f.b) {
      v1 = lut[lut_index(size, lower.r + 1, lower.g, lower.b)].rgb;
      v2 = lut[lut_index(size, lower.r + 1, lower.g + 1, lower.b)].rgb;
      weights = float4(1.0f - f.r, f.r - f.g, f.g - f.b, f.b);
    } else if (f.r >= f.b) {
      v1 = lut[lut_index(size, lower.r + 1, lower.g, lower.b)].rgb;
      v2 = lut[lut_index(size, lower.r + 1, lower.g, lower.b + 1)].rgb;
      weights = float4(1.0f - f.r, f.r - f.b, f.b - f.g, f.g);
    } else {
      v1 = lut[lut_index(size, lower.r, lower.g, lower.b + 1)].rgb;
      v2 = lut[lut_index(size, lower.r + 1, lower.g, lower.b + 1)].rgb;
      weights = float4(1.0f - f.b, f.b - f.r, f.r - f.g, f.g);
    }
  } else if (f.r >= f.b) {
    v1 = lut[lut_index(size, lower.r, lower.g + 1, lower.b)].rgb;
    v2 = lut[lut_index(size, lower.r + 1, lower.g + 1, lower.b)].rgb;
    weights = float4(1.0f - f.g, f.g - f.r, f.r - f.b, f.b);
  } else if (f.g >= f.b) {
    v1 = lut[lut_index(size, lower.r, lower.g + 1, lower.b)].rgb;
    v2 = lut[lut_index(size, lower.r, lower.g + 1, lower.b + 1)].rgb;
    weights = float4(1.0f - f.g, f.g - f.b, f.b - f.r, f.r);
  } else {
    v1 = lut[lut_index(size, lower.r, lower.g, lower.b + 1)].rgb;
    v2 = lut[lut_index(size, lower.r, lower.g + 1, lower.b + 1)].rgb;
    weights = float4(1.0f - f.b, f.b - f.g, f.g - f.r, f.r);
  }
  return c000 * weights.x + v1 * weights.y + v2 * weights.z +
         c111 * weights.w;
}

static float3 apply_black_point_compensation(
    float3 value,
    constant Aces2OutputLutUniforms& uniforms) {
  if (uniforms.black_point_compensation_enabled == 0) {
    return value;
  }
  float source_span = max(1.0e-6f, uniforms.black_point_headroom -
                                      uniforms.source_black_point);
  float output_span = max(0.0f, uniforms.black_point_headroom -
                                    uniforms.output_black_point);
  float3 normalized = (value - uniforms.source_black_point) / source_span;
  float3 remapped = uniforms.output_black_point + normalized * output_span;
  return select(
      clamp(remapped, 0.0f, uniforms.black_point_headroom),
      float3(uniforms.output_black_point),
      value <= uniforms.source_black_point);
}

static float4 apply_aces2_output_pixel(
    float4 source,
    device const float4* lut,
    constant Aces2OutputLutUniforms& uniforms) {
  float3 acescg = multiply_matrix(uniforms.working_to_acescg, source.rgb);
  acescg = clamp(acescg, 0.0f, uniforms.shaper_maximum);
  float denominator = log(1.0f + uniforms.shaper_maximum /
                                     uniforms.shaper_offset);
  float3 coordinate = log(1.0f + acescg / uniforms.shaper_offset) /
                      denominator;
  float3 target = tetrahedral_sample(lut, uniforms.lut_size, coordinate);
  target = clamp(target, 0.0f, uniforms.maximum_physical_rgb) *
           uniforms.physical_to_reference_white;
  target = apply_black_point_compensation(target, uniforms);
  target = clamp(target, 0.0f, uniforms.display_headroom);
  return float4(target, clamp(source.a, 0.0f, 1.0f));
}

static float3 linear_to_srgb(float3 value) {
  value = clamp(value, 0.0f, 1.0f);
  return select(
      1.055f * pow(value, float3(1.0f / 2.4f)) - 0.055f,
      12.92f * value,
      value <= 0.0031308f);
}

kernel void apply_aces2_output_lut(
    device float4* pixels [[buffer(0)]],
    device const float4* lut [[buffer(1)]],
    constant Aces2OutputLutUniforms& uniforms [[buffer(2)]],
    uint gid [[thread_position_in_grid]]) {
  uint count = uint(uniforms.width) * uint(uniforms.height);
  if (gid >= count) {
    return;
  }
  pixels[gid] = apply_aces2_output_pixel(pixels[gid], lut, uniforms);
}

kernel void apply_aces2_output_lut_target(
    device const float4* source [[buffer(0)]],
    device float4* destination [[buffer(1)]],
    device const float4* lut [[buffer(2)]],
    constant Aces2OutputLutUniforms& uniforms [[buffer(3)]],
    uint gid [[thread_position_in_grid]]) {
  uint count = uint(uniforms.width) * uint(uniforms.height);
  if (gid >= count) return;
  destination[gid] = apply_aces2_output_pixel(source[gid], lut, uniforms);
}

kernel void publish_aces2_output_lut_srgb8(
    device const float4* pixels [[buffer(0)]],
    device const float4* lut [[buffer(1)]],
    constant Aces2OutputLutUniforms& uniforms [[buffer(2)]],
    texture2d<float, access::write> output [[texture(0)]],
    uint2 gid [[thread_position_in_grid]]) {
  if (gid.x >= uint(uniforms.width) || gid.y >= uint(uniforms.height)) {
    return;
  }
  uint index = (gid.y + uint(uniforms.source_origin_y)) *
                   uint(uniforms.source_width) +
               gid.x + uint(uniforms.source_origin_x);
  float4 target = apply_aces2_output_pixel(pixels[index], lut, uniforms);
  output.write(float4(linear_to_srgb(target.rgb), target.a), gid);
}
)";
}

