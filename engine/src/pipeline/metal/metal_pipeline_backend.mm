[[nodiscard]] bool icc_lut_pixel_safe(
    const IccTransformLut3D& lut,
    const ColorPixel& pixel) {
  if (pixel.red < 0.0F || pixel.red > 1.0F || pixel.green < 0.0F ||
      pixel.green > 1.0F || pixel.blue < 0.0F || pixel.blue > 1.0F) {
    return false;
  }
  const auto cell_size = lut.settings.cube_size - 1;
  const auto coordinate = [&](float value) {
    const auto encoded = std::pow(
        static_cast<double>(value),
        lut.settings.input_shaper_exponent);
    return std::min(
        static_cast<int>(encoded * static_cast<double>(cell_size)),
        cell_size - 1);
  };
  const auto red = coordinate(pixel.red);
  const auto green = coordinate(pixel.green);
  const auto blue = coordinate(pixel.blue);
  const auto safe_size = static_cast<std::size_t>(cell_size);
  const auto index =
      (static_cast<std::size_t>(red) * safe_size +
       static_cast<std::size_t>(green)) *
          safe_size +
      static_cast<std::size_t>(blue);
  return lut.unsafe_cells[index] == 0U;
}

