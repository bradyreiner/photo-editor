bool MetalPipelineBackend::apply_aces2_output_lut_target(
    std::vector<ColorPixel>* pixels,
    int width,
    int height,
    const CompiledAces2OutputLutApplication& application,
    ColorAdjustmentTelemetry* telemetry) {
  const auto fail = [&](std::string reason) {
    if (telemetry != nullptr) {
      telemetry->gpu_fallback_reason = std::move(reason);
    }
    return false;
  };
  if (!available()) {
    return fail(unavailable_reason());
  }
  if (pixels == nullptr || !application.ready() || width <= 0 || height <= 0) {
    return fail("invalid_aces2_output_lut_request");
  }
  const auto& lut = *application.lut;
  const auto pixel_count =
      static_cast<std::size_t>(width) * static_cast<std::size_t>(height);
  if (pixels->size() != pixel_count) {
    return fail("aces2_output_lut_pixel_count_mismatch");
  }
  const auto finite_inputs = std::all_of(
      pixels->begin(),
      pixels->end(),
      [](const ColorPixel& pixel) {
        return std::isfinite(pixel.red) && std::isfinite(pixel.green) &&
               std::isfinite(pixel.blue) && std::isfinite(pixel.alpha);
      });
  if (!finite_inputs) {
    return fail("aces2_output_source_non_finite");
  }
  const auto finite_parameters =
      std::isfinite(application.black_point_headroom) &&
      std::isfinite(application.display_headroom) &&
      std::isfinite(application.source_black_point) &&
      std::isfinite(application.output_black_point);
  if (!finite_parameters) {
    return fail("aces2_output_application_non_finite");
  }
  const auto stage_start = std::chrono::steady_clock::now();
  auto lut_upload_bytes = std::size_t{0U};

  @autoreleasepool {
    id<MTLBuffer> active_lut_buffer =
        impl_->aces2_output_lut_buffer(lut, &lut_upload_bytes);
    if (!active_lut_buffer) {
      return fail("aces2_output_lut_buffer_allocation_failed");
    }

    const auto pixel_buffer_size = pixel_count * sizeof(ColorPixel);
    id<MTLBuffer> pixel_buffer = [impl_->device
        newBufferWithLength:pixel_buffer_size
                    options:MTLResourceStorageModeShared];
    if (!pixel_buffer) {
      return fail("aces2_output_pixel_buffer_allocation_failed");
    }
    std::memcpy([pixel_buffer contents], pixels->data(), pixel_buffer_size);

    const auto uniforms =
        make_aces2_output_lut_uniforms(application, width, height);

    id<MTLCommandBuffer> command_buffer = [impl_->command_queue commandBuffer];
    id<MTLComputeCommandEncoder> encoder =
        [command_buffer computeCommandEncoder];
    if (!command_buffer || !encoder) {
      return fail("aces2_output_command_encoder_unavailable");
    }
    [encoder setComputePipelineState:impl_->aces2_output_lut_pipeline];
    [encoder setBuffer:pixel_buffer offset:0 atIndex:0];
    [encoder setBuffer:active_lut_buffer offset:0 atIndex:1];
    [encoder setBytes:&uniforms length:sizeof(uniforms) atIndex:2];
    auto thread_group_size =
        impl_->aces2_output_lut_pipeline.maxTotalThreadsPerThreadgroup;
    thread_group_size = std::min<NSUInteger>(thread_group_size, 256U);
    [encoder dispatchThreads:MTLSizeMake(pixel_count, 1, 1)
         threadsPerThreadgroup:MTLSizeMake(thread_group_size, 1, 1)];
    [encoder endEncoding];
    [command_buffer commit];
    [command_buffer waitUntilCompleted];
    if (command_buffer.status != MTLCommandBufferStatusCompleted) {
      return fail("aces2_output_command_buffer_failed");
    }
    const auto* const output =
        static_cast<const ColorPixel*>([pixel_buffer contents]);
    for (std::size_t index = 0U; index < pixel_count; ++index) {
      const auto& pixel = output[index];
      const auto expected_alpha = std::clamp(
          static_cast<double>((*pixels)[index].alpha), 0.0, 1.0);
      if (!std::isfinite(pixel.red) || !std::isfinite(pixel.green) ||
          !std::isfinite(pixel.blue) || !std::isfinite(pixel.alpha) ||
          std::abs(static_cast<double>(pixel.alpha) - expected_alpha) >
              1.0e-6) {
        return fail("aces2_output_gpu_validation_failed");
      }
    }
    std::memcpy(pixels->data(), output, pixel_buffer_size);
    if (telemetry != nullptr) {
      telemetry->gpu_fallback_reason.clear();
      telemetry->final_output_ms += std::chrono::duration_cast<
          std::chrono::milliseconds>(
          std::chrono::steady_clock::now() - stage_start)
                                        .count();
      telemetry->gpu_cpu_to_gpu_bytes += static_cast<std::int64_t>(
          pixel_buffer_size + lut_upload_bytes);
      telemetry->gpu_gpu_to_cpu_bytes +=
          static_cast<std::int64_t>(pixel_buffer_size);
      telemetry->gpu_command_buffer_count += 1;
      telemetry->gpu_kernel_dispatch_count += 1;
    }
    return true;
  }
}

std::shared_ptr<const MetalOutputSurface>
MetalPipelineBackend::publish_aces2_output_lut_srgb8_surface(
    std::span<const ColorPixel> pixels,
    int width,
    int height,
    const CompiledAces2OutputLutApplication& application,
    ColorAdjustmentTelemetry* telemetry,
    CancellationToken cancellation,
    bool defer_completion) {
  const auto fail = [&](std::string reason) {
    if (telemetry != nullptr) {
      telemetry->gpu_fallback_reason = std::move(reason);
    }
    return std::shared_ptr<const MetalOutputSurface>{};
  };
  if (!available()) {
    return fail(unavailable_reason());
  }
  if (!application.ready() || width <= 0 || height <= 0 ||
      cancellation.cancelled()) {
    return fail(cancellation.cancelled()
                    ? "aces2_output_native_surface_cancelled"
                    : "invalid_aces2_output_native_surface_request");
  }
  const auto pixel_count =
      static_cast<std::size_t>(width) * static_cast<std::size_t>(height);
  if (pixels.size() != pixel_count) {
    return fail("aces2_output_native_surface_pixel_count_mismatch");
  }
  const auto finite_inputs = std::all_of(
      pixels.begin(), pixels.end(), [](const ColorPixel& pixel) {
        return std::isfinite(pixel.red) && std::isfinite(pixel.green) &&
               std::isfinite(pixel.blue) && std::isfinite(pixel.alpha);
      });
  const auto finite_parameters =
      std::isfinite(application.black_point_headroom) &&
      std::isfinite(application.display_headroom) &&
      std::isfinite(application.source_black_point) &&
      std::isfinite(application.output_black_point);
  if (!finite_inputs || !finite_parameters) {
    return fail("aces2_output_native_surface_non_finite");
  }

  const auto stage_start = std::chrono::steady_clock::now();
  auto lut_upload_bytes = std::size_t{0U};
  @autoreleasepool {
    id<MTLBuffer> lut_buffer = impl_->aces2_output_lut_buffer(
        *application.lut, &lut_upload_bytes);
    if (!lut_buffer) {
      return fail("aces2_output_native_lut_buffer_allocation_failed");
    }
    const auto pixel_buffer_size = pixel_count * sizeof(ColorPixel);
    id<MTLBuffer> pixel_buffer = [impl_->device
        newBufferWithLength:pixel_buffer_size
                    options:MTLResourceStorageModeShared];
    if (!pixel_buffer) {
      return fail("aces2_output_native_pixel_buffer_allocation_failed");
    }
    std::memcpy([pixel_buffer contents], pixels.data(), pixel_buffer_size);

    auto* descriptor = [MTLTextureDescriptor
        texture2DDescriptorWithPixelFormat:MTLPixelFormatBGRA8Unorm
                                     width:static_cast<NSUInteger>(width)
                                    height:static_cast<NSUInteger>(height)
                                 mipmapped:NO];
    descriptor.usage = MTLTextureUsageShaderRead | MTLTextureUsageShaderWrite;
    descriptor.storageMode = MTLStorageModeShared;
    id<MTLTexture> texture = [impl_->device newTextureWithDescriptor:descriptor];
    if (!texture) {
      return fail("aces2_output_native_texture_allocation_failed");
    }

    const auto uniforms =
        make_aces2_output_lut_uniforms(application, width, height);
    id<MTLCommandBuffer> command_buffer = [impl_->command_queue commandBuffer];
    id<MTLComputeCommandEncoder> encoder =
        [command_buffer computeCommandEncoder];
    if (!command_buffer || !encoder) {
      return fail("aces2_output_native_command_encoder_unavailable");
    }
    [encoder setComputePipelineState:impl_->aces2_output_lut_srgb8_pipeline];
    [encoder setBuffer:pixel_buffer offset:0 atIndex:0];
    [encoder setBuffer:lut_buffer offset:0 atIndex:1];
    [encoder setBytes:&uniforms length:sizeof(uniforms) atIndex:2];
    [encoder setTexture:texture atIndex:0];
    const auto thread_width = std::max<NSUInteger>(
        1U, impl_->aces2_output_lut_srgb8_pipeline.threadExecutionWidth);
    const auto thread_height = std::max<NSUInteger>(
        1U,
        impl_->aces2_output_lut_srgb8_pipeline.maxTotalThreadsPerThreadgroup /
            thread_width);
    [encoder dispatchThreads:MTLSizeMake(
                                 static_cast<NSUInteger>(width),
                                 static_cast<NSUInteger>(height),
                                 1)
         threadsPerThreadgroup:MTLSizeMake(thread_width, thread_height, 1)];
    [encoder endEncoding];
    id<MTLSharedEvent> ready_event =
        defer_completion ? [impl_->device newSharedEvent] : nil;
    const auto completion_deferred = ready_event != nil;
    if (completion_deferred) {
      [command_buffer encodeSignalEvent:ready_event value:1U];
      [command_buffer addCompletedHandler:^(id<MTLCommandBuffer> completed) {
        if (completed.status != MTLCommandBufferStatusCompleted &&
            ready_event.signaledValue < 1U) {
          ready_event.signaledValue = 1U;
        }
      }];
    }
    if (cancellation.cancelled()) {
      return fail("aces2_output_native_surface_cancelled");
    }
    [command_buffer commit];
    if (!completion_deferred) {
      [command_buffer waitUntilCompleted];
      if (command_buffer.status != MTLCommandBufferStatusCompleted) {
        return fail("aces2_output_native_command_buffer_failed");
      }
      if (cancellation.cancelled()) {
        return fail("aces2_output_native_surface_cancelled");
      }
    }

    auto surface_impl = std::make_shared<MetalOutputSurface::Impl>();
    surface_impl->texture = texture;
    surface_impl->producer_command_buffer = command_buffer;
    surface_impl->ready_event = ready_event;
    surface_impl->width = width;
    surface_impl->height = height;
    surface_impl->device_registry_id =
        static_cast<std::uint64_t>(impl_->device.registryID);
    surface_impl->ready_event_value = completion_deferred ? 1U : 0U;
    surface_impl->descriptor = srgb8_output_descriptor(width, height);
    if (telemetry != nullptr) {
      telemetry->gpu_fallback_reason.clear();
      telemetry->final_output_ms += std::chrono::duration_cast<
          std::chrono::milliseconds>(
          std::chrono::steady_clock::now() - stage_start)
                                        .count();
      telemetry->gpu_cpu_to_gpu_bytes += static_cast<std::int64_t>(
          pixel_buffer_size + lut_upload_bytes);
      telemetry->gpu_command_buffer_count += 1;
      telemetry->gpu_kernel_dispatch_count += 1;
    }
    return std::shared_ptr<const MetalOutputSurface>(
        new MetalOutputSurface(std::move(surface_impl)));
  }
}

std::shared_ptr<const MetalOutputSurface>
MetalPipelineBackend::publish_aces2_output_lut_srgb8_surface(
    const std::shared_ptr<const MetalWorkingSurface>& working_surface,
    const CompiledAces2OutputLutApplication& application,
    ColorAdjustmentTelemetry* telemetry,
    CancellationToken cancellation,
    bool defer_completion) {
  const auto descriptor = working_surface != nullptr
      ? working_surface->descriptor() : RenderSurfaceDescriptor{};
  return publish_aces2_output_lut_srgb8_surface(
      working_surface, 0, 0, static_cast<int>(descriptor.width),
      static_cast<int>(descriptor.height), application, telemetry,
      cancellation, defer_completion);
}

std::shared_ptr<const MetalOutputSurface>
MetalPipelineBackend::publish_aces2_output_lut_srgb8_surface(
    const std::shared_ptr<const MetalWorkingSurface>& working_surface,
    int source_x,
    int source_y,
    int width,
    int height,
    const CompiledAces2OutputLutApplication& application,
    ColorAdjustmentTelemetry* telemetry,
    CancellationToken cancellation,
    bool defer_completion) {
  const auto fail = [&](std::string reason) {
    if (telemetry != nullptr) {
      telemetry->gpu_fallback_reason = std::move(reason);
    }
    return std::shared_ptr<const MetalOutputSurface>{};
  };
  if (!available()) {
    return fail(unavailable_reason());
  }
  if (working_surface == nullptr || !application.ready() ||
      cancellation.cancelled()) {
    return fail(cancellation.cancelled()
                    ? "aces2_output_native_surface_cancelled"
                    : "invalid_aces2_output_native_working_surface_request");
  }
  const auto source_descriptor = working_surface->descriptor();
  const auto source_width = static_cast<int>(source_descriptor.width);
  const auto source_height = static_cast<int>(source_descriptor.height);
  const auto finite_parameters =
      std::isfinite(application.black_point_headroom) &&
      std::isfinite(application.display_headroom) &&
      std::isfinite(application.source_black_point) &&
      std::isfinite(application.output_black_point);
  if (width <= 0 || height <= 0 || source_x < 0 || source_y < 0 ||
      source_x > source_width - width || source_y > source_height - height ||
      !finite_parameters ||
      !working_surface->valid_for(source_descriptor) ||
      working_surface->device_registry_id() !=
          static_cast<std::uint64_t>(impl_->device.registryID) ||
      working_surface->impl_->pixel_buffer == nil ||
      working_surface->impl_->ready_event == nil) {
    return fail("aces2_output_native_working_surface_invalid");
  }

  const auto stage_start = std::chrono::steady_clock::now();
  auto lut_upload_bytes = std::size_t{0U};
  @autoreleasepool {
    id<MTLBuffer> lut_buffer = impl_->aces2_output_lut_buffer(
        *application.lut, &lut_upload_bytes);
    if (lut_buffer == nil) {
      return fail("aces2_output_native_lut_buffer_allocation_failed");
    }
    auto* texture_descriptor = [MTLTextureDescriptor
        texture2DDescriptorWithPixelFormat:MTLPixelFormatBGRA8Unorm
                                     width:static_cast<NSUInteger>(width)
                                    height:static_cast<NSUInteger>(height)
                                 mipmapped:NO];
    texture_descriptor.usage =
        MTLTextureUsageShaderRead | MTLTextureUsageShaderWrite;
    texture_descriptor.storageMode = MTLStorageModeShared;
    id<MTLTexture> texture =
        [impl_->device newTextureWithDescriptor:texture_descriptor];
    if (texture == nil) {
      return fail("aces2_output_native_texture_allocation_failed");
    }

    const auto uniforms = make_aces2_output_lut_uniforms(
        application, width, height, source_width, source_x, source_y);
    id<MTLCommandBuffer> command_buffer = [impl_->command_queue commandBuffer];
    if (command_buffer == nil) {
      return fail("aces2_output_native_command_encoder_unavailable");
    }
    [command_buffer encodeWaitForEvent:working_surface->impl_->ready_event
                                 value:working_surface->impl_->ready_event_value];
    id<MTLComputeCommandEncoder> encoder =
        [command_buffer computeCommandEncoder];
    if (encoder == nil) {
      return fail("aces2_output_native_command_encoder_unavailable");
    }
    [encoder setComputePipelineState:impl_->aces2_output_lut_srgb8_pipeline];
    [encoder setBuffer:working_surface->impl_->pixel_buffer offset:0 atIndex:0];
    [encoder setBuffer:lut_buffer offset:0 atIndex:1];
    [encoder setBytes:&uniforms length:sizeof(uniforms) atIndex:2];
    [encoder setTexture:texture atIndex:0];
    const auto thread_width = std::max<NSUInteger>(
        1U, impl_->aces2_output_lut_srgb8_pipeline.threadExecutionWidth);
    const auto thread_height = std::max<NSUInteger>(
        1U,
        impl_->aces2_output_lut_srgb8_pipeline.maxTotalThreadsPerThreadgroup /
            thread_width);
    [encoder dispatchThreads:MTLSizeMake(
                                 static_cast<NSUInteger>(width),
                                 static_cast<NSUInteger>(height),
                                 1)
         threadsPerThreadgroup:MTLSizeMake(thread_width, thread_height, 1)];
    [encoder endEncoding];
    id<MTLSharedEvent> ready_event =
        defer_completion ? [impl_->device newSharedEvent] : nil;
    const auto completion_deferred = ready_event != nil;
    if (completion_deferred) {
      [command_buffer encodeSignalEvent:ready_event value:1U];
      [command_buffer addCompletedHandler:^(id<MTLCommandBuffer> completed) {
        if (completed.status != MTLCommandBufferStatusCompleted &&
            ready_event.signaledValue < 1U) {
          ready_event.signaledValue = 1U;
        }
      }];
    }
    if (cancellation.cancelled()) {
      return fail("aces2_output_native_surface_cancelled");
    }
    [command_buffer commit];
    if (!completion_deferred) {
      [command_buffer waitUntilCompleted];
      if (command_buffer.status != MTLCommandBufferStatusCompleted ||
          !working_surface->producer_completed_successfully()) {
        return fail("aces2_output_native_command_buffer_failed");
      }
      if (cancellation.cancelled()) {
        return fail("aces2_output_native_surface_cancelled");
      }
    }

    auto surface_impl = std::make_shared<MetalOutputSurface::Impl>();
    surface_impl->texture = texture;
    surface_impl->producer_command_buffer = command_buffer;
    surface_impl->ready_event = ready_event;
    surface_impl->upstream_surface = working_surface;
    surface_impl->width = width;
    surface_impl->height = height;
    surface_impl->device_registry_id =
        static_cast<std::uint64_t>(impl_->device.registryID);
    surface_impl->ready_event_value = completion_deferred ? 1U : 0U;
    surface_impl->descriptor = srgb8_output_descriptor(width, height);
    if (telemetry != nullptr) {
      telemetry->gpu_fallback_reason.clear();
      telemetry->final_output_ms += std::chrono::duration_cast<
          std::chrono::milliseconds>(
          std::chrono::steady_clock::now() - stage_start)
                                        .count();
      telemetry->gpu_cpu_to_gpu_bytes +=
          static_cast<std::int64_t>(lut_upload_bytes);
      telemetry->gpu_command_buffer_count += 1;
      telemetry->gpu_kernel_dispatch_count += 1;
    }
    return std::shared_ptr<const MetalOutputSurface>(
        new MetalOutputSurface(std::move(surface_impl)));
  }
}

std::shared_ptr<const MetalOutputSurface>
MetalPipelineBackend::publish_aces2_output_lut_icc_bgra8_surface(
    const std::shared_ptr<const MetalWorkingSurface>& working_surface,
    const CompiledAces2OutputLutApplication& application,
    const IccTransformLut3D& device_lut,
    const CompiledIccTransform& exact_device_transform,
    const RenderSurfaceDescriptor& publish_output,
    ColorAdjustmentTelemetry* telemetry,
    CancellationToken cancellation,
    bool defer_completion) {
  const auto fail = [&](std::string reason) {
    if (telemetry != nullptr) {
      telemetry->gpu_fallback_reason = std::move(reason);
    }
    return std::shared_ptr<const MetalOutputSurface>{};
  };
  if (!available()) {
    return fail(unavailable_reason());
  }
  if (working_surface == nullptr || !application.ready() || !device_lut.valid() ||
      !exact_device_transform.ready() ||
      device_lut.transform_cache_key !=
          exact_device_transform.description().cache_key || cancellation.cancelled()) {
    return fail(cancellation.cancelled()
                    ? "aces2_icc_native_surface_cancelled"
                    : "invalid_aces2_icc_native_surface_request");
  }
  const auto source_descriptor = working_surface->descriptor();
  const auto width = static_cast<int>(source_descriptor.width);
  const auto height = static_cast<int>(source_descriptor.height);
  const auto finite_parameters =
      std::isfinite(application.black_point_headroom) &&
      std::isfinite(application.display_headroom) &&
      std::isfinite(application.source_black_point) &&
      std::isfinite(application.output_black_point);
  if (width <= 0 || height <= 0 || !finite_parameters ||
      application.display_headroom > 1.0 + 1.0e-9 ||
      !working_surface->valid_for(source_descriptor) ||
      working_surface->device_registry_id() !=
          static_cast<std::uint64_t>(impl_->device.registryID) ||
      working_surface->impl_->pixel_buffer == nil ||
      working_surface->impl_->ready_event == nil ||
      publish_output.pixel_encoding != RenderPixelEncoding::DisplayEncodedFloat ||
      publish_output.color_domain != RenderColorDomain::Device ||
      publish_output.range != RenderRangeModel::DisplayBounded ||
      publish_output.alpha != RenderAlphaModel::Straight ||
      publish_output.color_space_identity.empty() ||
      publish_output.transfer_identity.empty() ||
      publish_output.width != source_descriptor.width ||
      publish_output.height != source_descriptor.height) {
    return fail("aces2_icc_native_surface_contract_invalid");
  }

  const auto stage_start = std::chrono::steady_clock::now();
  auto output_lut_upload_bytes = std::size_t{0U};
  auto icc_lut_upload_bytes = std::size_t{0U};
  @autoreleasepool {
    id<MTLBuffer> output_lut_buffer = impl_->aces2_output_lut_buffer(
        *application.lut, &output_lut_upload_bytes);
    if (output_lut_buffer == nil) {
      return fail("aces2_icc_native_output_lut_allocation_failed");
    }

    id<MTLBuffer> icc_table_buffer = nil;
    id<MTLBuffer> icc_unsafe_cells_buffer = nil;
    {
      const std::scoped_lock lock(impl_->icc_transform_lut_mutex);
      const auto cached = std::find_if(
          impl_->icc_transform_lut_buffers.begin(),
          impl_->icc_transform_lut_buffers.end(),
          [&](const Impl::IccTransformLutBufferEntry& entry) {
            return entry.key == device_lut.cache_key;
          });
      if (cached != impl_->icc_transform_lut_buffers.end()) {
        cached->last_use = ++impl_->icc_transform_lut_use_counter;
        icc_table_buffer = cached->table_buffer;
        icc_unsafe_cells_buffer = cached->unsafe_cells_buffer;
      } else {
        const auto table_bytes = device_lut.table.size() * sizeof(IccRgbaFloat);
        const auto unsafe_bytes =
            device_lut.unsafe_cells.size() * sizeof(std::uint8_t);
        id<MTLBuffer> uploaded_table = [impl_->device
            newBufferWithLength:table_bytes
                        options:MTLResourceStorageModeShared];
        id<MTLBuffer> uploaded_unsafe = [impl_->device
            newBufferWithLength:unsafe_bytes
                        options:MTLResourceStorageModeShared];
        if (uploaded_table == nil || uploaded_unsafe == nil) {
          return fail("aces2_icc_native_device_lut_allocation_failed");
        }
        std::memcpy([uploaded_table contents], device_lut.table.data(), table_bytes);
        std::memcpy(
            [uploaded_unsafe contents],
            device_lut.unsafe_cells.data(),
            unsafe_bytes);
        if (impl_->icc_transform_lut_buffers.size() >= 2U) {
          const auto least_recently_used = std::min_element(
              impl_->icc_transform_lut_buffers.begin(),
              impl_->icc_transform_lut_buffers.end(),
              [](const Impl::IccTransformLutBufferEntry& left,
                 const Impl::IccTransformLutBufferEntry& right) {
                return left.last_use < right.last_use;
              });
          impl_->icc_transform_lut_buffers.erase(least_recently_used);
        }
        impl_->icc_transform_lut_buffers.push_back({
            .key = device_lut.cache_key,
            .table_buffer = uploaded_table,
            .unsafe_cells_buffer = uploaded_unsafe,
            .last_use = ++impl_->icc_transform_lut_use_counter,
        });
        icc_table_buffer = uploaded_table;
        icc_unsafe_cells_buffer = uploaded_unsafe;
        icc_lut_upload_bytes = table_bytes + unsafe_bytes;
      }
    }
    if (icc_table_buffer == nil || icc_unsafe_cells_buffer == nil) {
      return fail("aces2_icc_native_device_lut_unavailable");
    }

    const auto pixel_count = static_cast<std::size_t>(width) *
                             static_cast<std::size_t>(height);
    const auto pixel_buffer_size = pixel_count * sizeof(ColorPixel);
    id<MTLBuffer> target_buffer = [impl_->device
        newBufferWithLength:pixel_buffer_size
                    options:MTLResourceStorageModePrivate];
    if (target_buffer == nil) {
      return fail("aces2_icc_native_target_buffer_allocation_failed");
    }
    auto* texture_descriptor = [MTLTextureDescriptor
        texture2DDescriptorWithPixelFormat:MTLPixelFormatBGRA8Unorm
                                     width:static_cast<NSUInteger>(width)
                                    height:static_cast<NSUInteger>(height)
                                 mipmapped:NO];
    texture_descriptor.usage =
        MTLTextureUsageShaderRead | MTLTextureUsageShaderWrite;
    texture_descriptor.storageMode = MTLStorageModeShared;
    id<MTLTexture> texture =
        [impl_->device newTextureWithDescriptor:texture_descriptor];
    if (texture == nil) {
      return fail("aces2_icc_native_texture_allocation_failed");
    }

    const auto output_uniforms =
        make_aces2_output_lut_uniforms(application, width, height);
    const auto icc_uniforms = IccTransformLutUniforms{
        .input_shaper_exponent =
            static_cast<float>(device_lut.settings.input_shaper_exponent),
        .lut_size = device_lut.settings.cube_size,
        .width = width,
        .height = height,
    };
    if (pixel_count > std::numeric_limits<std::uint32_t>::max()) {
      return fail("aces2_icc_native_pixel_count_exceeds_uint32");
    }
    id<MTLBuffer> exact_count_buffer = [impl_->device
        newBufferWithLength:sizeof(std::uint32_t)
                    options:MTLResourceStorageModeShared];
    if (exact_count_buffer == nil) {
      return fail("aces2_icc_native_exact_count_allocation_failed");
    }
    *static_cast<std::uint32_t*>([exact_count_buffer contents]) = 0U;

    id<MTLCommandBuffer> initial_command_buffer =
        [impl_->command_queue commandBuffer];
    if (initial_command_buffer == nil) {
      return fail("aces2_icc_native_command_buffer_unavailable");
    }
    [initial_command_buffer encodeWaitForEvent:working_surface->impl_->ready_event
                                         value:working_surface->impl_->ready_event_value];
    id<MTLComputeCommandEncoder> output_encoder =
        [initial_command_buffer computeCommandEncoder];
    if (output_encoder == nil) {
      return fail("aces2_icc_native_output_encoder_unavailable");
    }
    [output_encoder
        setComputePipelineState:impl_->aces2_output_lut_target_pipeline];
    [output_encoder setBuffer:working_surface->impl_->pixel_buffer
                       offset:0
                      atIndex:0];
    [output_encoder setBuffer:target_buffer offset:0 atIndex:1];
    [output_encoder setBuffer:output_lut_buffer offset:0 atIndex:2];
    [output_encoder setBytes:&output_uniforms
                      length:sizeof(output_uniforms)
                     atIndex:3];
    auto output_thread_group_size =
        impl_->aces2_output_lut_target_pipeline.maxTotalThreadsPerThreadgroup;
    output_thread_group_size =
        std::min<NSUInteger>(output_thread_group_size, 256U);
    [output_encoder dispatchThreads:MTLSizeMake(pixel_count, 1, 1)
              threadsPerThreadgroup:MTLSizeMake(output_thread_group_size, 1, 1)];
    [output_encoder endEncoding];

    id<MTLComputeCommandEncoder> count_encoder =
        [initial_command_buffer computeCommandEncoder];
    if (count_encoder == nil) {
      return fail("aces2_icc_native_exact_count_encoder_unavailable");
    }
    [count_encoder setComputePipelineState:impl_->icc_exact_count_pipeline];
    [count_encoder setBuffer:target_buffer offset:0 atIndex:0];
    [count_encoder setBuffer:icc_unsafe_cells_buffer offset:0 atIndex:1];
    [count_encoder setBytes:&icc_uniforms length:sizeof(icc_uniforms) atIndex:2];
    [count_encoder setBuffer:exact_count_buffer offset:0 atIndex:3];
    auto count_thread_group_size =
        impl_->icc_exact_count_pipeline.maxTotalThreadsPerThreadgroup;
    count_thread_group_size =
        std::min<NSUInteger>(count_thread_group_size, 256U);
    [count_encoder dispatchThreads:MTLSizeMake(pixel_count, 1, 1)
             threadsPerThreadgroup:MTLSizeMake(count_thread_group_size, 1, 1)];
    [count_encoder endEncoding];

    id<MTLComputeCommandEncoder> device_encoder =
        [initial_command_buffer computeCommandEncoder];
    if (device_encoder == nil) {
      return fail("aces2_icc_native_device_encoder_unavailable");
    }
    [device_encoder setComputePipelineState:impl_->icc_transform_lut_bgra8_pipeline];
    [device_encoder setBuffer:target_buffer offset:0 atIndex:0];
    [device_encoder setBuffer:icc_table_buffer offset:0 atIndex:1];
    [device_encoder setBytes:&icc_uniforms length:sizeof(icc_uniforms) atIndex:2];
    [device_encoder setTexture:texture atIndex:0];
    const auto device_thread_width = std::max<NSUInteger>(
        1U, impl_->icc_transform_lut_bgra8_pipeline.threadExecutionWidth);
    const auto device_thread_height = std::max<NSUInteger>(
        1U,
        impl_->icc_transform_lut_bgra8_pipeline.maxTotalThreadsPerThreadgroup /
            device_thread_width);
    [device_encoder dispatchThreads:MTLSizeMake(
                                        static_cast<NSUInteger>(width),
                                        static_cast<NSUInteger>(height),
                                        1)
              threadsPerThreadgroup:MTLSizeMake(
                                        device_thread_width,
                                        device_thread_height,
                                        1)];
    [device_encoder endEncoding];
    if (cancellation.cancelled()) {
      return fail("aces2_icc_native_surface_cancelled");
    }
    [initial_command_buffer commit];
    [initial_command_buffer waitUntilCompleted];
    if (initial_command_buffer.status != MTLCommandBufferStatusCompleted ||
        !working_surface->producer_completed_successfully()) {
      return fail("aces2_icc_native_initial_command_buffer_failed");
    }
    if (cancellation.cancelled()) {
      return fail("aces2_icc_native_surface_cancelled");
    }

    const auto exact_count = static_cast<std::size_t>(
        *static_cast<const std::uint32_t*>([exact_count_buffer contents]));
    constexpr auto kMaximumExactSubsetPixels = std::size_t{1'048'576U};
    const auto maximum_exact_subset = std::min(
        kMaximumExactSubsetPixels,
        std::max(std::size_t{1U}, pixel_count / 4U));
    if (exact_count > maximum_exact_subset) {
      if (telemetry != nullptr) {
        telemetry->gpu_cpu_to_gpu_bytes += static_cast<std::int64_t>(
            output_lut_upload_bytes + icc_lut_upload_bytes +
            sizeof(std::uint32_t));
        telemetry->gpu_gpu_to_cpu_bytes += sizeof(std::uint32_t);
        telemetry->gpu_command_buffer_count += 1;
        telemetry->gpu_kernel_dispatch_count += 3;
      }
      return fail("aces2_icc_native_exact_subset_exceeds_budget");
    }

    id<MTLCommandBuffer> producer_command_buffer = initial_command_buffer;
    id<MTLSharedEvent> ready_event = nil;
    auto completion_deferred = false;
    auto command_buffer_count = std::int64_t{1};
    auto kernel_dispatch_count = std::int64_t{3};
    auto cpu_to_gpu_bytes = output_lut_upload_bytes + icc_lut_upload_bytes +
                            sizeof(std::uint32_t);
    auto gpu_to_cpu_bytes = sizeof(std::uint32_t);
    if (exact_count > 0U) {
      const auto exact_pixel_bytes = exact_count * sizeof(IccRgbaFloat);
      const auto exact_index_bytes = exact_count * sizeof(std::uint32_t);
      id<MTLBuffer> exact_pixels_buffer = [impl_->device
          newBufferWithLength:exact_pixel_bytes
                      options:MTLResourceStorageModeShared];
      id<MTLBuffer> exact_indices_buffer = [impl_->device
          newBufferWithLength:exact_index_bytes
                      options:MTLResourceStorageModeShared];
      if (exact_pixels_buffer == nil || exact_indices_buffer == nil) {
        return fail("aces2_icc_native_exact_subset_allocation_failed");
      }
      *static_cast<std::uint32_t*>([exact_count_buffer contents]) = 0U;
      id<MTLCommandBuffer> compact_command_buffer =
          [impl_->command_queue commandBuffer];
      id<MTLComputeCommandEncoder> compact_encoder =
          [compact_command_buffer computeCommandEncoder];
      if (compact_command_buffer == nil || compact_encoder == nil) {
        return fail("aces2_icc_native_exact_compact_encoder_unavailable");
      }
      [compact_encoder setComputePipelineState:impl_->icc_exact_compact_pipeline];
      [compact_encoder setBuffer:target_buffer offset:0 atIndex:0];
      [compact_encoder setBuffer:icc_unsafe_cells_buffer offset:0 atIndex:1];
      [compact_encoder setBytes:&icc_uniforms length:sizeof(icc_uniforms) atIndex:2];
      [compact_encoder setBuffer:exact_count_buffer offset:0 atIndex:3];
      [compact_encoder setBuffer:exact_pixels_buffer offset:0 atIndex:4];
      [compact_encoder setBuffer:exact_indices_buffer offset:0 atIndex:5];
      auto compact_thread_group_size =
          impl_->icc_exact_compact_pipeline.maxTotalThreadsPerThreadgroup;
      compact_thread_group_size =
          std::min<NSUInteger>(compact_thread_group_size, 256U);
      [compact_encoder dispatchThreads:MTLSizeMake(pixel_count, 1, 1)
               threadsPerThreadgroup:MTLSizeMake(
                                         compact_thread_group_size, 1, 1)];
      [compact_encoder endEncoding];
      [compact_command_buffer commit];
      [compact_command_buffer waitUntilCompleted];
      if (compact_command_buffer.status != MTLCommandBufferStatusCompleted ||
          cancellation.cancelled() ||
          static_cast<std::size_t>(*static_cast<const std::uint32_t*>(
              [exact_count_buffer contents])) != exact_count) {
        return fail(cancellation.cancelled()
                        ? "aces2_icc_native_surface_cancelled"
                        : "aces2_icc_native_exact_compaction_failed");
      }

      auto exact_pixels = std::vector<IccRgbaFloat>(exact_count);
      std::memcpy(
          exact_pixels.data(), [exact_pixels_buffer contents], exact_pixel_bytes);
      const auto source_alpha = [&]() {
        auto values = std::vector<float>{};
        values.reserve(exact_count);
        for (const auto& pixel : exact_pixels) {
          values.push_back(pixel.alpha);
        }
        return values;
      }();
      if (!exact_device_transform.apply(exact_pixels) || cancellation.cancelled()) {
        return fail(cancellation.cancelled()
                        ? "aces2_icc_native_surface_cancelled"
                        : "aces2_icc_native_exact_transform_failed");
      }
      for (auto index = std::size_t{0U}; index < exact_pixels.size(); ++index) {
        const auto& pixel = exact_pixels[index];
        if (!std::isfinite(pixel.red) || !std::isfinite(pixel.green) ||
            !std::isfinite(pixel.blue) || !std::isfinite(pixel.alpha) ||
            pixel.alpha != source_alpha[index]) {
          return fail("aces2_icc_native_exact_transform_output_invalid");
        }
      }
      std::memcpy(
          [exact_pixels_buffer contents], exact_pixels.data(), exact_pixel_bytes);

      id<MTLCommandBuffer> patch_command_buffer =
          [impl_->command_queue commandBuffer];
      id<MTLComputeCommandEncoder> patch_encoder =
          [patch_command_buffer computeCommandEncoder];
      if (patch_command_buffer == nil || patch_encoder == nil) {
        return fail("aces2_icc_native_exact_patch_encoder_unavailable");
      }
      const auto exact_count_u32 = static_cast<std::uint32_t>(exact_count);
      const auto width_u32 = static_cast<std::uint32_t>(width);
      [patch_encoder setComputePipelineState:impl_->icc_exact_patch_bgra8_pipeline];
      [patch_encoder setBuffer:exact_pixels_buffer offset:0 atIndex:0];
      [patch_encoder setBuffer:exact_indices_buffer offset:0 atIndex:1];
      [patch_encoder setBytes:&exact_count_u32
                       length:sizeof(exact_count_u32)
                      atIndex:2];
      [patch_encoder setBytes:&width_u32 length:sizeof(width_u32) atIndex:3];
      [patch_encoder setTexture:texture atIndex:0];
      auto patch_thread_group_size =
          impl_->icc_exact_patch_bgra8_pipeline.maxTotalThreadsPerThreadgroup;
      patch_thread_group_size =
          std::min<NSUInteger>(patch_thread_group_size, 256U);
      [patch_encoder dispatchThreads:MTLSizeMake(exact_count, 1, 1)
             threadsPerThreadgroup:MTLSizeMake(patch_thread_group_size, 1, 1)];
      [patch_encoder endEncoding];
      ready_event = defer_completion ? [impl_->device newSharedEvent] : nil;
      completion_deferred = ready_event != nil;
      if (completion_deferred) {
        [patch_command_buffer encodeSignalEvent:ready_event value:1U];
        [patch_command_buffer addCompletedHandler:^(id<MTLCommandBuffer> completed) {
          if (completed.status != MTLCommandBufferStatusCompleted &&
              ready_event.signaledValue < 1U) {
            ready_event.signaledValue = 1U;
          }
        }];
      }
      [patch_command_buffer commit];
      if (!completion_deferred) {
        [patch_command_buffer waitUntilCompleted];
        if (patch_command_buffer.status != MTLCommandBufferStatusCompleted) {
          return fail("aces2_icc_native_exact_patch_failed");
        }
      }
      producer_command_buffer = patch_command_buffer;
      command_buffer_count += 2;
      kernel_dispatch_count += 2;
      cpu_to_gpu_bytes += sizeof(std::uint32_t) + exact_pixel_bytes;
      gpu_to_cpu_bytes += sizeof(std::uint32_t) + exact_pixel_bytes +
                          exact_index_bytes;
    }

    auto surface_impl = std::make_shared<MetalOutputSurface::Impl>();
    surface_impl->texture = texture;
    surface_impl->producer_command_buffer = producer_command_buffer;
    surface_impl->ready_event = ready_event;
    surface_impl->upstream_surface = working_surface;
    surface_impl->width = width;
    surface_impl->height = height;
    surface_impl->device_registry_id =
        static_cast<std::uint64_t>(impl_->device.registryID);
    surface_impl->ready_event_value = completion_deferred ? 1U : 0U;
    surface_impl->descriptor = publish_output;
    if (telemetry != nullptr) {
      telemetry->gpu_fallback_reason.clear();
      telemetry->final_output_ms += std::chrono::duration_cast<
          std::chrono::milliseconds>(
          std::chrono::steady_clock::now() - stage_start)
                                        .count();
      telemetry->gpu_cpu_to_gpu_bytes +=
          static_cast<std::int64_t>(cpu_to_gpu_bytes);
      telemetry->gpu_gpu_to_cpu_bytes +=
          static_cast<std::int64_t>(gpu_to_cpu_bytes);
      telemetry->gpu_command_buffer_count += command_buffer_count;
      telemetry->gpu_kernel_dispatch_count += kernel_dispatch_count;
    }
    return std::shared_ptr<const MetalOutputSurface>(
        new MetalOutputSurface(std::move(surface_impl)));
  }
}

bool MetalPipelineBackend::apply_icc_transform_lut(
    std::span<IccRgbaFloat> pixels,
    int width,
    int height,
    const IccTransformLut3D& lut,
    const CompiledIccTransform& exact_transform,
    IccTransformLutApplyStats* apply_stats,
    ColorAdjustmentTelemetry* telemetry) {
  if (apply_stats != nullptr) {
    *apply_stats = {};
  }
  if (!available() || width <= 0 || height <= 0 ||
      !lut.valid() || !exact_transform.ready() ||
      lut.transform_cache_key != exact_transform.description().cache_key) {
    return false;
  }
  const auto pixel_count =
      static_cast<std::size_t>(width) * static_cast<std::size_t>(height);
  if (pixels.size() != pixel_count) {
    return false;
  }
  const auto finite_inputs = std::all_of(
      pixels.begin(),
      pixels.end(),
      [](const IccRgbaFloat& pixel) {
        return std::isfinite(pixel.red) && std::isfinite(pixel.green) &&
               std::isfinite(pixel.blue) && std::isfinite(pixel.alpha);
      });
  if (!finite_inputs) {
    return false;
  }

  std::vector<IccRgbaFloat> exact_pixels;
  std::vector<std::size_t> exact_indices;
  exact_pixels.reserve(pixel_count / 16U + 1U);
  exact_indices.reserve(exact_pixels.capacity());
  for (std::size_t index = 0U; index < pixel_count; ++index) {
    const auto& pixel = pixels[index];
    if (icc_lut_pixel_safe(
            lut,
            ColorPixel{
                .red = pixel.red,
                .green = pixel.green,
                .blue = pixel.blue,
                .alpha = pixel.alpha,
            })) {
      continue;
    }
    exact_pixels.push_back({
        .red = pixel.red,
        .green = pixel.green,
        .blue = pixel.blue,
        .alpha = pixel.alpha,
    });
    exact_indices.push_back(index);
  }
  if (!exact_pixels.empty() && !exact_transform.apply(exact_pixels)) {
    return false;
  }
  for (std::size_t index = 0U; index < exact_pixels.size(); ++index) {
    const auto& transformed = exact_pixels[index];
    const auto source_index = exact_indices[index];
    if (!std::isfinite(transformed.red) || !std::isfinite(transformed.green) ||
        !std::isfinite(transformed.blue) ||
        !std::isfinite(transformed.alpha) ||
        transformed.alpha != pixels[source_index].alpha) {
      return false;
    }
  }

  const auto stage_start = std::chrono::steady_clock::now();
  auto resource_upload_bytes = std::size_t{0U};
  const std::scoped_lock lock(impl_->icc_transform_lut_mutex);
  @autoreleasepool {
    id<MTLBuffer> table_buffer = nil;
    id<MTLBuffer> unsafe_cells_buffer = nil;
    const auto cached = std::find_if(
        impl_->icc_transform_lut_buffers.begin(),
        impl_->icc_transform_lut_buffers.end(),
        [&](const Impl::IccTransformLutBufferEntry& entry) {
          return entry.key == lut.cache_key;
        });
    if (cached != impl_->icc_transform_lut_buffers.end()) {
      cached->last_use = ++impl_->icc_transform_lut_use_counter;
      table_buffer = cached->table_buffer;
      unsafe_cells_buffer = cached->unsafe_cells_buffer;
    } else {
      const auto table_bytes = lut.table.size() * sizeof(IccRgbaFloat);
      const auto unsafe_bytes =
          lut.unsafe_cells.size() * sizeof(std::uint8_t);
      id<MTLBuffer> uploaded_table = [impl_->device
          newBufferWithLength:table_bytes
                      options:MTLResourceStorageModeShared];
      id<MTLBuffer> uploaded_unsafe_cells = [impl_->device
          newBufferWithLength:unsafe_bytes
                      options:MTLResourceStorageModeShared];
      if (!uploaded_table || !uploaded_unsafe_cells) {
        return false;
      }
      std::memcpy([uploaded_table contents], lut.table.data(), table_bytes);
      std::memcpy(
          [uploaded_unsafe_cells contents],
          lut.unsafe_cells.data(),
          unsafe_bytes);
      if (impl_->icc_transform_lut_buffers.size() >= 2U) {
        const auto least_recently_used = std::min_element(
            impl_->icc_transform_lut_buffers.begin(),
            impl_->icc_transform_lut_buffers.end(),
            [](const Impl::IccTransformLutBufferEntry& left,
               const Impl::IccTransformLutBufferEntry& right) {
              return left.last_use < right.last_use;
            });
        impl_->icc_transform_lut_buffers.erase(least_recently_used);
      }
      impl_->icc_transform_lut_buffers.push_back({
          .key = lut.cache_key,
          .table_buffer = uploaded_table,
          .unsafe_cells_buffer = uploaded_unsafe_cells,
          .last_use = ++impl_->icc_transform_lut_use_counter,
      });
      table_buffer = uploaded_table;
      unsafe_cells_buffer = uploaded_unsafe_cells;
      resource_upload_bytes = table_bytes + unsafe_bytes;
    }

    const auto pixel_buffer_size = pixel_count * sizeof(IccRgbaFloat);
    id<MTLBuffer> pixel_buffer = [impl_->device
        newBufferWithLength:pixel_buffer_size
                    options:MTLResourceStorageModeShared];
    if (!pixel_buffer) {
      return false;
    }
    std::memcpy([pixel_buffer contents], pixels.data(), pixel_buffer_size);
    const auto uniforms = IccTransformLutUniforms{
        .input_shaper_exponent =
            static_cast<float>(lut.settings.input_shaper_exponent),
        .lut_size = lut.settings.cube_size,
        .width = width,
        .height = height,
    };
    id<MTLCommandBuffer> command_buffer = [impl_->command_queue commandBuffer];
    id<MTLComputeCommandEncoder> encoder =
        [command_buffer computeCommandEncoder];
    if (!command_buffer || !encoder) {
      return false;
    }
    [encoder setComputePipelineState:impl_->icc_transform_lut_pipeline];
    [encoder setBuffer:pixel_buffer offset:0 atIndex:0];
    [encoder setBuffer:table_buffer offset:0 atIndex:1];
    [encoder setBuffer:unsafe_cells_buffer offset:0 atIndex:2];
    [encoder setBytes:&uniforms length:sizeof(uniforms) atIndex:3];
    auto thread_group_size =
        impl_->icc_transform_lut_pipeline.maxTotalThreadsPerThreadgroup;
    thread_group_size = std::min<NSUInteger>(thread_group_size, 256U);
    [encoder dispatchThreads:MTLSizeMake(pixel_count, 1, 1)
         threadsPerThreadgroup:MTLSizeMake(thread_group_size, 1, 1)];
    [encoder endEncoding];
    [command_buffer commit];
    [command_buffer waitUntilCompleted];
    if (command_buffer.status != MTLCommandBufferStatusCompleted) {
      return false;
    }

    const auto* const gpu_output =
        static_cast<const IccRgbaFloat*>([pixel_buffer contents]);
    for (std::size_t index = 0U; index < pixel_count; ++index) {
      const auto& pixel = gpu_output[index];
      if (!std::isfinite(pixel.red) || !std::isfinite(pixel.green) ||
          !std::isfinite(pixel.blue) || !std::isfinite(pixel.alpha) ||
          pixel.alpha != pixels[index].alpha) {
        return false;
      }
    }
    std::memcpy(pixels.data(), gpu_output, pixel_buffer_size);
    for (std::size_t index = 0U; index < exact_pixels.size(); ++index) {
      const auto& exact = exact_pixels[index];
      pixels[exact_indices[index]] = {
          .red = exact.red,
          .green = exact.green,
          .blue = exact.blue,
          .alpha = exact.alpha,
      };
    }
    if (apply_stats != nullptr) {
      apply_stats->lut_pixels = pixel_count - exact_pixels.size();
      apply_stats->exact_fallback_pixels = exact_pixels.size();
    }
    if (telemetry != nullptr) {
      telemetry->final_output_ms += std::chrono::duration_cast<
          std::chrono::milliseconds>(
          std::chrono::steady_clock::now() - stage_start)
                                        .count();
      telemetry->gpu_cpu_to_gpu_bytes += static_cast<std::int64_t>(
          pixel_buffer_size + resource_upload_bytes);
      telemetry->gpu_gpu_to_cpu_bytes +=
          static_cast<std::int64_t>(pixel_buffer_size);
      telemetry->gpu_command_buffer_count += 1;
      telemetry->gpu_kernel_dispatch_count += 1;
    }
    return true;
  }
}

bool MetalPipelineBackend::apply_ocio_project_gpu_program(
    std::vector<ColorPixel>* pixels,
    int width,
    int height,
    const OcioProjectGpuProgram& program,
    std::string* failure_reason,
    ColorAdjustmentTelemetry* telemetry) {
  const auto fail = [&](std::string reason) {
    if (failure_reason != nullptr) {
      *failure_reason = std::move(reason);
    }
    return false;
  };
  if (!available()) {
    return fail(unavailable_reason());
  }
  if (pixels == nullptr || width <= 0 || height <= 0 || !program.ready()) {
    return fail("invalid_ocio_project_gpu_request");
  }
  const auto pixel_count =
      static_cast<std::size_t>(width) * static_cast<std::size_t>(height);
  if (pixels->size() != pixel_count ||
      pixel_count > std::numeric_limits<std::uint32_t>::max()) {
    return fail("invalid_ocio_project_gpu_dimensions");
  }
  const auto& description = program.description();
  if (description.program_cache_key.empty() ||
      description.shader_sha256.size() != 64U ||
      description.resource_sha256.size() != 64U ||
      description.uniform_count != 0U ||
      description.uniform_buffer_bytes != 0U) {
    return fail("unsupported_ocio_project_gpu_program");
  }
  const auto full_shader = ocio_project_compute_shader_source(description);
  if (full_shader.empty()) {
    return fail("invalid_ocio_project_gpu_shader_contract");
  }
  const auto stage_start = std::chrono::steady_clock::now();
  auto resource_upload_bytes = std::size_t{0U};

  const std::scoped_lock program_lock(impl_->ocio_project_gpu_mutex);
  @autoreleasepool {
    auto cached = std::find_if(
        impl_->ocio_project_gpu_pipelines.begin(),
        impl_->ocio_project_gpu_pipelines.end(),
        [&](const Impl::OcioProjectGpuPipelineEntry& entry) {
          return entry.key == description.program_cache_key;
        });
    if (cached == impl_->ocio_project_gpu_pipelines.end()) {
      NSError* library_error = nil;
      const auto source = [NSString stringWithUTF8String:full_shader.c_str()];
      const auto library = [impl_->device
          newLibraryWithSource:source
                       options:color_compile_options()
                         error:&library_error];
      if (!library) {
        const auto detail = library_error != nil
                                ? [[library_error localizedDescription] UTF8String]
                                : "unknown";
        return fail(std::string("ocio_project_msl_compile_failed:") +
                    (detail != nullptr ? detail : "unknown"));
      }
      const auto function = [library
          newFunctionWithName:@"photo_editor_apply_ocio_project"];
      if (!function) {
        return fail("ocio_project_msl_function_unavailable");
      }
      NSError* pipeline_error = nil;
      const auto pipeline = [impl_->device
          newComputePipelineStateWithFunction:function
                                         error:&pipeline_error];
      if (!pipeline) {
        const auto detail = pipeline_error != nil
                                ? [[pipeline_error localizedDescription] UTF8String]
                                : "unknown";
        return fail(std::string("ocio_project_msl_pipeline_failed:") +
                    (detail != nullptr ? detail : "unknown"));
      }

      Impl::OcioProjectGpuPipelineEntry entry;
      entry.key = description.program_cache_key;
      entry.pipeline = pipeline;
      entry.last_use = ++impl_->ocio_project_gpu_use_counter;
      entry.textures.reserve(description.textures.size());
      entry.samplers.reserve(description.textures.size());
      for (const auto& texture : description.textures) {
        if ((texture.channels != 1U && texture.channels != 3U) ||
            texture.width == 0U || texture.height == 0U ||
            texture.depth == 0U || texture.values.empty()) {
          return fail("invalid_ocio_project_gpu_texture");
        }
        const auto pixel_format = texture.channels == 1U
                                      ? MTLPixelFormatR32Float
                                      : MTLPixelFormatRGBA32Float;
        auto* texture_descriptor = [[MTLTextureDescriptor alloc] init];
        texture_descriptor.textureType =
            texture.kind == OcioProjectGpuTextureKind::OneDimensional
                ? MTLTextureType1D
                : (texture.kind == OcioProjectGpuTextureKind::TwoDimensional
                       ? MTLTextureType2D
                       : MTLTextureType3D);
        texture_descriptor.pixelFormat = pixel_format;
        texture_descriptor.width = texture.width;
        texture_descriptor.height = texture.height;
        texture_descriptor.depth = texture.depth;
        texture_descriptor.mipmapLevelCount = 1U;
        texture_descriptor.storageMode = MTLStorageModeShared;
        texture_descriptor.usage = MTLTextureUsageShaderRead;
        const auto metal_texture =
            [impl_->device newTextureWithDescriptor:texture_descriptor];
        if (!metal_texture) {
          return fail("ocio_project_gpu_texture_allocation_failed");
        }
        const auto texel_count =
            texture.width * texture.height * texture.depth;
        const auto bytes_per_pixel = texture.channels == 1U
                                         ? sizeof(float)
                                         : sizeof(float) * 4U;
        std::vector<float> expanded;
        const float* upload_values = texture.values.data();
        if (texture.channels == 3U) {
          expanded.resize(texel_count * 4U);
          for (std::size_t index = 0U; index < texel_count; ++index) {
            expanded[index * 4U] = texture.values[index * 3U];
            expanded[index * 4U + 1U] = texture.values[index * 3U + 1U];
            expanded[index * 4U + 2U] = texture.values[index * 3U + 2U];
            expanded[index * 4U + 3U] = 1.0F;
          }
          upload_values = expanded.data();
        }
        const auto bytes_per_row = texture.width * bytes_per_pixel;
        const auto bytes_per_image = texture.height * bytes_per_row;
        [metal_texture
            replaceRegion:MTLRegionMake3D(
                              0U,
                              0U,
                              0U,
                              texture.width,
                              texture.height,
                              texture.depth)
             mipmapLevel:0U
                   slice:0U
               withBytes:upload_values
             bytesPerRow:bytes_per_row
           bytesPerImage:bytes_per_image];

        auto* sampler_descriptor = [[MTLSamplerDescriptor alloc] init];
        const auto nearest = texture.interpolation == "nearest";
        sampler_descriptor.minFilter =
            nearest ? MTLSamplerMinMagFilterNearest
                    : MTLSamplerMinMagFilterLinear;
        sampler_descriptor.magFilter = sampler_descriptor.minFilter;
        sampler_descriptor.mipFilter = MTLSamplerMipFilterNotMipmapped;
        sampler_descriptor.sAddressMode = MTLSamplerAddressModeClampToEdge;
        sampler_descriptor.tAddressMode = MTLSamplerAddressModeClampToEdge;
        sampler_descriptor.rAddressMode = MTLSamplerAddressModeClampToEdge;
        const auto sampler =
            [impl_->device newSamplerStateWithDescriptor:sampler_descriptor];
        if (!sampler) {
          return fail("ocio_project_gpu_sampler_allocation_failed");
        }
        entry.textures.push_back(metal_texture);
        entry.samplers.push_back(sampler);
        resource_upload_bytes += texel_count * bytes_per_pixel;
      }
      if (impl_->ocio_project_gpu_pipelines.size() >= 4U) {
        const auto least_recently_used = std::min_element(
            impl_->ocio_project_gpu_pipelines.begin(),
            impl_->ocio_project_gpu_pipelines.end(),
            [](const Impl::OcioProjectGpuPipelineEntry& left,
               const Impl::OcioProjectGpuPipelineEntry& right) {
              return left.last_use < right.last_use;
            });
        impl_->ocio_project_gpu_pipelines.erase(least_recently_used);
      }
      impl_->ocio_project_gpu_pipelines.push_back(std::move(entry));
      cached = std::prev(impl_->ocio_project_gpu_pipelines.end());
    } else {
      cached->last_use = ++impl_->ocio_project_gpu_use_counter;
    }

    const auto pixel_buffer_bytes = pixel_count * sizeof(ColorPixel);
    const auto pixel_buffer = [impl_->device
        newBufferWithBytes:pixels->data()
                    length:pixel_buffer_bytes
                   options:MTLResourceStorageModeShared];
    if (!pixel_buffer) {
      return fail("ocio_project_gpu_pixel_buffer_allocation_failed");
    }
    const auto command_buffer = [impl_->command_queue commandBuffer];
    const auto encoder = [command_buffer computeCommandEncoder];
    if (!command_buffer || !encoder) {
      return fail("ocio_project_gpu_command_encoder_unavailable");
    }
    [encoder setComputePipelineState:cached->pipeline];
    [encoder setBuffer:pixel_buffer offset:0U atIndex:0U];
    const auto metal_pixel_count = static_cast<std::uint32_t>(pixel_count);
    [encoder setBytes:&metal_pixel_count
               length:sizeof(metal_pixel_count)
              atIndex:1U];
    for (std::size_t index = 0U; index < description.textures.size(); ++index) {
      const auto binding = description.textures[index].binding_index;
      [encoder setTexture:cached->textures[index] atIndex:binding];
      [encoder setSamplerState:cached->samplers[index] atIndex:binding];
    }
    auto thread_group_size = cached->pipeline.maxTotalThreadsPerThreadgroup;
    thread_group_size = std::min<NSUInteger>(thread_group_size, 256U);
    [encoder dispatchThreads:MTLSizeMake(pixel_count, 1U, 1U)
         threadsPerThreadgroup:MTLSizeMake(thread_group_size, 1U, 1U)];
    [encoder endEncoding];
    [command_buffer commit];
    [command_buffer waitUntilCompleted];
    if (command_buffer.status != MTLCommandBufferStatusCompleted) {
      const auto error = command_buffer.error;
      const auto detail = error != nil ? [[error localizedDescription] UTF8String]
                                       : "unknown";
      return fail(std::string("ocio_project_gpu_dispatch_failed:") +
                  (detail != nullptr ? detail : "unknown"));
    }

    auto transformed = *pixels;
    std::memcpy(
        transformed.data(), [pixel_buffer contents], pixel_buffer_bytes);
    for (std::size_t index = 0U; index < transformed.size(); ++index) {
      if (!std::isfinite(transformed[index].red) ||
          !std::isfinite(transformed[index].green) ||
          !std::isfinite(transformed[index].blue) ||
          !std::isfinite(transformed[index].alpha) ||
          transformed[index].alpha != (*pixels)[index].alpha) {
        return fail("ocio_project_gpu_output_validation_failed");
      }
    }
    *pixels = std::move(transformed);
    if (failure_reason != nullptr) {
      failure_reason->clear();
    }
    if (telemetry != nullptr) {
      telemetry->final_output_ms += std::chrono::duration_cast<
          std::chrono::milliseconds>(
          std::chrono::steady_clock::now() - stage_start)
                                        .count();
      telemetry->gpu_cpu_to_gpu_bytes += static_cast<std::int64_t>(
          pixel_buffer_bytes + resource_upload_bytes);
      telemetry->gpu_gpu_to_cpu_bytes +=
          static_cast<std::int64_t>(pixel_buffer_bytes);
      telemetry->gpu_command_buffer_count += 1;
      telemetry->gpu_kernel_dispatch_count += 1;
    }
    return true;
  }
}

std::shared_ptr<const MetalWorkingSurface>
MetalPipelineBackend::publish_masks_and_color_lut_surface(
    std::span<const ColorPixel> pixels,
    int width,
    int height,
    const ColorAdjustmentState& state,
    const ColorLut3D& lut,
    const RenderSurfaceDescriptor& descriptor,
    ColorAdjustmentTelemetry* telemetry,
    CancellationToken cancellation,
    double scene_exposure_gain,
    bool apply_color_lut,
    const CompiledToneStageLut* tone_lut,
    const CompiledCurveStageLuts* curve_luts,
    const CompiledLookStageProgram* look_program,
    const CompiledUserLutStageProgram* user_lut_program) {
  const auto fail = [&](std::string reason) {
    if (telemetry != nullptr) {
      telemetry->gpu_fallback_reason = std::move(reason);
    }
  };
  if (!available()) {
    fail(unavailable_reason());
    return {};
  }
  if (cancellation.cancelled()) {
    fail("fused_masks_color_lut_cancelled");
    return {};
  }
  if (pixels.empty() || (apply_color_lut && !lut.valid) ||
      (tone_lut != nullptr && !tone_lut->ready()) ||
      (curve_luts != nullptr && !curve_luts->ready()) ||
      (look_program != nullptr && !look_program->ready()) ||
      (user_lut_program != nullptr && !user_lut_program->ready()) ||
      width <= 0 || height <= 0 ||
      !std::isfinite(scene_exposure_gain) || scene_exposure_gain <= 0.0 ||
      descriptor.width != static_cast<std::uint32_t>(width) ||
      descriptor.height != static_cast<std::uint32_t>(height)) {
    fail("invalid_fused_masks_color_lut_request");
    return {};
  }
  const auto pixel_count =
      static_cast<std::size_t>(width) *
      static_cast<std::size_t>(height);
  const auto lut_edge =
      lut.size > 0
          ? static_cast<std::size_t>(lut.size)
          : std::size_t{0U};
  if (pixel_count >
          std::numeric_limits<std::size_t>::max() /
              sizeof(ColorPixel) ||
      pixel_count > std::numeric_limits<std::uint32_t>::max() ||
      pixels.size() != pixel_count) {
    fail("fused_masks_color_lut_pixel_count_mismatch");
    return {};
  }
  if (!std::ranges::all_of(pixels, [](const ColorPixel& pixel) {
        return std::isfinite(pixel.red) && std::isfinite(pixel.green) &&
               std::isfinite(pixel.blue) && std::isfinite(pixel.alpha);
      })) {
    fail("fused_masks_color_lut_source_non_finite");
    return {};
  }
  const auto geometry_program =
      compile_geometry_stage_program(state, width, height);
  if (!geometry_program.ready()) {
    fail("fused_geometry_program_invalid");
    return {};
  }
  const auto apply_geometry = geometry_program.active;
  const auto hdr_local_tone_program =
      compile_hdr_local_tone_program(state, width, height);
  if (!hdr_local_tone_program.ready()) {
    fail("fused_hdr_local_tone_program_invalid");
    return {};
  }
  const auto apply_hdr_local_tone = hdr_local_tone_program.active();
  if (apply_hdr_local_tone && tone_lut == nullptr) {
    fail("fused_hdr_local_tone_requires_tone_lut");
    return {};
  }
  std::shared_ptr<const CachedFillLayerPixels> cached_layer_pixels;
  {
    // Snapshot only the most recently used payload, preserving the existing
    // cache limits. The strong buffer owner pins shared storage even if another
    // publication evicts it before this program reaches the encoding lock.
    const std::scoped_lock cache_lock(impl_->color_lut_mutex);
    if (!impl_->layer_pixel_buffers.empty()) {
      const auto latest = std::max_element(impl_->layer_pixel_buffers.begin(), impl_->layer_pixel_buffers.end(),
          [](const auto& a, const auto& b) { return a.last_use < b.last_use; });
      auto owner = std::make_shared<Impl::LayerPixelBufferEntry>(*latest);
      cached_layer_pixels = std::make_shared<CachedFillLayerPixels>(CachedFillLayerPixels{
          .pixels = {static_cast<const ColorPixel*>([owner->buffer contents]),
              static_cast<std::size_t>(owner->bytes / sizeof(ColorPixel))},
          .owner = std::move(owner), .identity = latest->identity});
    }
  }
  const auto fill_layer_program = compile_fill_layer_program(state, width, height, std::move(cached_layer_pixels));
  if (!fill_layer_program.ready()) {
    fail("fused_fill_layer_program_invalid");
    return {};
  }
  const auto apply_fill_layers = fill_layer_program.active();
  const auto apply_layer_spatial_detail = std::ranges::any_of(
      fill_layer_program.layers.cbegin(),
      fill_layer_program.layers.cbegin() + fill_layer_program.layer_count,
      [](const auto& layer) { return layer.has_spatial_detail; });
  const auto apply_layer_fine_detail = std::ranges::any_of(
      fill_layer_program.layers.cbegin(),
      fill_layer_program.layers.cbegin() + fill_layer_program.layer_count,
      [](const auto& layer) { return layer.has_fine_detail; });
  const auto apply_layer_geometry = std::ranges::any_of(
      fill_layer_program.layers.cbegin(),
      fill_layer_program.layers.cbegin() + fill_layer_program.layer_count,
      [](const auto& layer) { return layer.has_geometry; });
  const auto apply_layer_user_lut = std::ranges::any_of(
      fill_layer_program.layers.cbegin(),
      fill_layer_program.layers.cbegin() + fill_layer_program.layer_count,
      [](const auto& layer) { return layer.has_user_lut; });
  const auto spatial_detail_program =
      compile_interactive_spatial_detail_program(state, width, height);
  if (!spatial_detail_program.ready()) {
    fail("fused_spatial_detail_program_invalid");
    return {};
  }
  const auto apply_spatial_detail = spatial_detail_program.active();
  const auto fine_detail_program =
      compile_fine_detail_program(state, width, height);
  if (!fine_detail_program.ready()) {
    fail("fused_fine_detail_program_invalid");
    return {};
  }
  const auto apply_fine_detail = fine_detail_program.active();
  if (tone_lut != nullptr &&
      (!std::ranges::all_of(
           tone_lut->samples,
           [](float sample) { return std::isfinite(sample); }) ||
       !std::ranges::all_of(
           tone_lut->luminance_coefficients,
           [](float coefficient) { return std::isfinite(coefficient); }) ||
       !std::isfinite(tone_lut->stop_step) || tone_lut->stop_step <= 0.0F ||
       !std::isfinite(tone_lut->output_headroom) ||
       tone_lut->output_headroom < 1.0F)) {
    fail("fused_tone_lut_invalid");
    return {};
  }
