bool MetalWorkingSurface::copy_pixels(
    std::vector<ColorPixel>* destination,
    CancellationToken cancellation) const {
  if (destination == nullptr || cancellation.cancelled() || impl_ == nullptr ||
      !valid_for(impl_->descriptor)) {
    return false;
  }
  @autoreleasepool {
    [impl_->producer_command_buffer waitUntilCompleted];
    if (cancellation.cancelled() || !producer_completed_successfully()) {
      return false;
    }
    auto materialized = std::vector<ColorPixel>(
        static_cast<std::size_t>(impl_->descriptor.width) *
        static_cast<std::size_t>(impl_->descriptor.height));
    std::memcpy(
        materialized.data(), [impl_->pixel_buffer contents], impl_->byte_size);
    if (!std::ranges::all_of(materialized, [](const ColorPixel& pixel) {
          return std::isfinite(pixel.red) && std::isfinite(pixel.green) &&
                 std::isfinite(pixel.blue) && std::isfinite(pixel.alpha);
        })) {
      return false;
    }
    *destination = std::move(materialized);
  }
  return true;
}

