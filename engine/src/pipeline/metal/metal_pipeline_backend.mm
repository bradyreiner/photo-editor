bool MetalOutputSurface::copy_pixels(
    std::vector<ColorPixel>* destination,
    CancellationToken cancellation) const {
  if (destination == nullptr || cancellation.cancelled() || impl_ == nullptr) {
    return false;
  }
  auto encoded = std::vector<std::uint8_t>(
      static_cast<std::size_t>(std::max(width(), 0)) *
      static_cast<std::size_t>(std::max(height(), 0)) * 4U);
  if (!copy_bgra8_pixels_for_testing(encoded) || cancellation.cancelled()) {
    return false;
  }
  auto materialized = std::vector<ColorPixel>(encoded.size() / 4U);
  constexpr auto kCodeScale = 1.0F / 255.0F;
  for (auto index = std::size_t{0}; index < materialized.size(); ++index) {
    const auto offset = index * 4U;
    materialized[index] = ColorPixel{
        .red = static_cast<float>(encoded[offset + 2U]) * kCodeScale,
        .green = static_cast<float>(encoded[offset + 1U]) * kCodeScale,
        .blue = static_cast<float>(encoded[offset]) * kCodeScale,
        .alpha = static_cast<float>(encoded[offset + 3U]) * kCodeScale,
    };
  }
  *destination = std::move(materialized);
  return true;
}

