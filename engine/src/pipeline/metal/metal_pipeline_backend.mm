kernel void apply_icc_transform_lut(
    device float4* pixels [[buffer(0)]],
    device const float4* lut [[buffer(1)]],
    device const uchar* unsafe_cells [[buffer(2)]],
    constant IccTransformLutUniforms& uniforms [[buffer(3)]],
    uint gid [[thread_position_in_grid]]) {
  uint count = uint(uniforms.width) * uint(uniforms.height);
  if (gid >= count) {
    return;
  }
  float4 source = pixels[gid];
  if (any(source.rgb < 0.0f) || any(source.rgb > 1.0f)) {
    return;
  }
  float3 coordinate = pow(source.rgb, uniforms.input_shaper_exponent);
  int cell_size = uniforms.lut_size - 1;
  int3 cell = min(int3(coordinate * float(cell_size)), int3(cell_size - 1));
  if (unsafe_cells[icc_lut_index(cell_size, cell.r, cell.g, cell.b)] != 0) {
    return;
  }
  float3 output = icc_tetrahedral_sample(
      lut, uniforms.lut_size, coordinate);
  pixels[gid] = float4(output, source.a);
}

