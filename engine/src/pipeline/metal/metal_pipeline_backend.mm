  [[nodiscard]] id<MTLBuffer> aces2_output_lut_buffer(
      const Aces2OutputLut3D& lut,
      std::size_t* upload_bytes) {
    if (upload_bytes != nullptr) {
      *upload_bytes = 0U;
    }
    const std::scoped_lock lock(aces2_output_lut_mutex);
    const auto cached = std::find_if(
        aces2_output_lut_buffers.begin(),
        aces2_output_lut_buffers.end(),
        [&](const Aces2OutputLutBufferEntry& entry) {
          return entry.key == lut.cache_key;
        });
    if (cached != aces2_output_lut_buffers.end()) {
      cached->last_use = ++aces2_output_lut_use_counter;
      return cached->buffer;
    }
    const auto buffer_size = lut.byte_size();
    id<MTLBuffer> buffer = [device
        newBufferWithLength:buffer_size
                    options:MTLResourceStorageModeShared];
    if (!buffer) {
      return nil;
    }
    std::memcpy([buffer contents], lut.table.data(), buffer_size);
    if (aces2_output_lut_buffers.size() >= 2U) {
      const auto least_recently_used = std::min_element(
          aces2_output_lut_buffers.begin(),
          aces2_output_lut_buffers.end(),
          [](const Aces2OutputLutBufferEntry& left,
             const Aces2OutputLutBufferEntry& right) {
            return left.last_use < right.last_use;
          });
      aces2_output_lut_buffers.erase(least_recently_used);
    }
    aces2_output_lut_buffers.push_back(Aces2OutputLutBufferEntry{
        .key = lut.cache_key,
        .buffer = buffer,
        .last_use = ++aces2_output_lut_use_counter,
    });
    if (upload_bytes != nullptr) {
      *upload_bytes = buffer_size;
    }
    return buffer;
  }
