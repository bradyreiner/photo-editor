}

inline bool icc_pixel_requires_exact_transform(
    float4 source,
    device const uchar* unsafe_cells,
    constant IccTransformLutUniforms& uniforms) {
  if (any(!isfinite(source)) || any(source.rgb < 0.0f) ||
      any(source.rgb > 1.0f)) {
    return true;
  }
  float3 coordinate = pow(source.rgb, uniforms.input_shaper_exponent);
  int cell_size = uniforms.lut_size - 1;
  int3 cell = min(int3(coordinate * float(cell_size)), int3(cell_size - 1));
  return unsafe_cells[icc_lut_index(
      cell_size, cell.r, cell.g, cell.b)] != 0;
}

