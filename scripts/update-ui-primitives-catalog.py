#!/usr/bin/env python3
"""Refresh the UI Primitives index from the actual shared QML inventory."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COMPONENTS = ROOT / "apps/desktop/qml/components"
LIVE = {
    "Theme", "AppIcon", "ActionButton", "ToolButton", "MiniButton", "MenuButton",
    "SplitButton", "FilterChip", "ColorSwatchButton", "ToneTextField", "ToneTextArea",
    "ToneComboBox", "ToneCheckBox", "ToneSpinBox", "InspectorSlider", "InspectorSection",
    "StudioCollapsibleGroup", "PreferenceNavRow", "ImportSourceRow", "ImportFolderRow", "StatusChip", "InfoPill",
    "ActivityBanner", "ActivityStatusBar", "ProgressStrip", "InlineActivityIndicator", "OpticalActivityIndicator",
    "StudioMetadataRow", "StudioEmptyStateCard", "StudioPanel",
}
FAMILIES = [
    (r"Theme|Glass|BrandPanel|Surface|SectionHeader|SectionTitle|RowRule|Skeleton", "Foundations", "Use shared color, type, geometry, and spacing tokens."),
    (r"Slider|SpinBox|TextField|TextArea|CheckBox|ComboBox|Curve|ColorWheel|ColorSwatch|Picker", "Inputs", "Review value entry, reset, disabled reasons, focus, and density."),
    (r"Inspector|Collapsible|Panel|Dock", "Panels & inspectors", "Converge on section hierarchy and explicit panel controls."),
    (r"Status|Activity|Progress|Indicator|Banner|EmptyState|InfoPill|Metadata|Metric|Diagnostic", "Feedback", "Separate information from actions; make status readable without color alone."),
    (r"Nav|Rail|Sidebar|Tab|ToolRail", "Navigation", "Distinguish selection from keyboard focus; keep destinations discoverable."),
    (r"Button|Menu|Chip|Command|ToolTip|Icon", "Commands", "Align command roles, hover, press, focus, selection, and disabled behavior."),
    (r"Dialog|Popup|Sheet|Popover|Walkthrough|FirstRun", "Dialogs & overlays", "Review focus entry and return, escape, sizing, and clear action hierarchy."),
    (r"Row|Tile|Card|Thumb|Strip|Layer", "Rows & collections", "Review selection, row actions, long labels, empty states, and scrolling."),
]


def entry(name):
    family, plan = next(
        ((family, plan) for pattern, family, plan in FAMILIES if re.search(pattern, name)),
        ("Workspace compositions", "Review in its actual workflow before adopting shared primitives."),
    )
    return {"name": name, "family": family, "status": "Live specimen" if name in LIVE else "Workspace review", "plan": plan}


components = [entry(path.stem) for path in sorted(COMPONENTS.glob("*.qml")) if not path.stem.startswith("UiPrimitives")]
icons = sorted(set(re.findall(r'case "([^\"]+)":', (COMPONENTS / "AppIcon.qml").read_text())))
output = ".pragma library\n\n// Generated by scripts/update-ui-primitives-catalog.py.\n// Coverage describes examples, not visual or workflow qualification.\n"
output += "var components = " + json.dumps(components, indent=4) + "\n\n"
output += "var iconNames = " + json.dumps(icons, indent=4) + "\n"
(COMPONENTS / "UiPrimitiveCatalog.js").write_text(output)
print(f"Indexed {len(components)} components and {len(icons)} icon names.")
