#!/usr/bin/env node
// Generate reviewable D1 staff enrollment SQL. This tool never connects to D1.
import { open, unlink } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const ROLES = new Set(['support', 'admin']);
const CONTROL_CHARACTERS = /[\u0000-\u001f\u007f-\u009f]/u;

function requiredText(value, label, maxLength) {
  if (typeof value !== 'string' || value.length === 0 || value.trim() !== value || value.length > maxLength || CONTROL_CHARACTERS.test(value)) {
    throw new TypeError(`${label} must be 1-${maxLength} characters with no surrounding whitespace or control characters`);
  }
  return value;
}

function literal(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

function validateCommon(input) {
  if (!input || typeof input !== 'object' || Array.isArray(input)) throw new TypeError('Options are required');
  return {
    subject: requiredText(input.subject, 'subject', 255),
    actor: requiredText(input.actor, 'actor', 255),
    reason: requiredText(input.reason, 'reason', 500),
    createdAt: input.createdAt === undefined ? Math.floor(Date.now() / 1000) : input.createdAt,
  };
}

function timestamp(value) {
  if (!Number.isSafeInteger(value) || value < 0) throw new TypeError('createdAt must be a non-negative safe integer Unix timestamp');
  return String(value);
}

function header(operation) {
  return [
    '-- Generated by scripts/staff-access.mjs. Review before applying.',
    '-- This file contains staff identity data. Keep it private and remove it after use.',
    '-- Wrangler D1 execute applies a SQL file transactionally; do not add BEGIN/COMMIT.',
    `-- Operation: ${operation}`,
    '',
  ].join('\n');
}

function auditInsert({ actor, action, target, reason, createdAt }) {
  return `INSERT INTO audit (id, actor, action, target, reason, created_at)
SELECT lower(hex(randomblob(16))), ${literal(actor)}, ${literal(action)}, ${literal(target)}, ${literal(reason)}, ${timestamp(createdAt)}
WHERE changes() > 0;`;
}

export function generateGrantSql(input) {
  const common = validateCommon(input);
  const role = input.role;
  if (!ROLES.has(role)) throw new TypeError('role must be support or admin');

  const subject = literal(common.subject);
  const sql = `INSERT INTO staff (subject, role)
VALUES (${subject}, ${literal(role)})
ON CONFLICT(subject) DO UPDATE SET role = excluded.role
WHERE staff.role = excluded.role;

${auditInsert({ ...common, action: `staff_grant:${role}`, target: `staff:${common.subject}` })}`;
  return header(`grant ${role}`) + sql + '\n';
}

export function generateRevokeSql(input) {
  const common = validateCommon(input);
  const subject = literal(common.subject);
  const sql = `DELETE FROM staff
WHERE subject = ${subject}
  AND (role != 'admin' OR EXISTS (SELECT 1 FROM staff AS another_admin WHERE another_admin.role = 'admin' AND another_admin.subject != ${subject}));

${auditInsert({ ...common, action: 'staff_revoke', target: `staff:${common.subject}` })}`;
  return header('revoke') + sql + '\n';
}

export function usage() {
  return `Usage:
  node scripts/staff-access.mjs grant --subject <Access-subject> --role <support|admin> --actor <operator-subject> --reason <text> --out <file>
  node scripts/staff-access.mjs revoke --subject <Access-subject> --actor <operator-subject> --reason <text> --out <file>

Generates SQL only. It never reads credentials, contacts Cloudflare, or executes SQL.
The output file is created exclusively with mode 0600; an existing path is never overwritten.
Grant is idempotent for the requested role and will not change a subject's existing role.
To change a role, revoke that exact subject and then generate a new grant. Revoke protects
the last admin account. Review the generated file before manually applying it.

Options:
  --subject  Exact Cloudflare Access JWT sub to enroll or revoke
  --role     Required for grant; one of support or admin
  --actor    Required operator Cloudflare Access subject for the audit entry
  --reason   Required audit reason
  --out      Required new SQL file path
  --help     Show this help
`;
}

function parseArgs(args) {
  const [command, ...rest] = args;
  if (command === '--help' || command === '-h' || command === 'help') return { help: true };
  if (!['grant', 'revoke'].includes(command)) throw new TypeError('command must be grant or revoke');
  const values = new Map();
  for (let index = 0; index < rest.length; index += 1) {
    const flag = rest[index];
    if (!['--subject', '--role', '--actor', '--reason', '--out'].includes(flag)) throw new TypeError(`unknown option: ${flag}`);
    if (values.has(flag)) throw new TypeError(`option may only be supplied once: ${flag}`);
    const value = rest[index + 1];
    if (value === undefined || value.startsWith('--')) throw new TypeError(`missing value for ${flag}`);
    values.set(flag, value);
    index += 1;
  }
  for (const required of ['--subject', '--actor', '--reason', '--out']) {
    if (!values.has(required)) throw new TypeError(`missing required option: ${required}`);
  }
  if (command === 'grant' && !values.has('--role')) throw new TypeError('grant requires --role');
  if (command === 'revoke' && values.has('--role')) throw new TypeError('revoke does not accept --role');
  return {
    command,
    options: {
      subject: values.get('--subject'),
      role: values.get('--role'),
      actor: values.get('--actor'),
      reason: values.get('--reason'),
      output: values.get('--out'),
    },
  };
}

export async function runCli(args, { stdout = process.stdout, stderr = process.stderr } = {}) {
  let parsed;
  try {
    parsed = parseArgs(args);
    if (parsed.help) {
      stdout.write(usage());
      return 0;
    }
    const { output, ...options } = parsed.options;
    const sql = parsed.command === 'grant' ? generateGrantSql(options) : generateRevokeSql(options);
    const path = resolve(output);
    const file = await open(path, 'wx', 0o600);
    try {
      await file.writeFile(sql, { encoding: 'utf8' });
      await file.sync();
      await file.close();
    } catch (error) {
      await file.close().catch(() => {});
      await unlink(path).catch(() => {});
      throw error;
    }
    stdout.write(`Generated ${parsed.command} SQL at ${path}. Review before applying; no database was contacted.\n`);
    return 0;
  } catch (error) {
    stderr.write(`${error instanceof Error ? error.message : 'Could not generate staff SQL'}\n`);
    return 2;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  process.exitCode = await runCli(process.argv.slice(2));
}
